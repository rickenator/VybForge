"""EXL3 4bpw reference dequant (verification-only Python; numpy).

Pins the reconstruction recipe read off exllamav3 (TensorFold's engine) source
reconstruct.cu / exl3_dq.cuh / codebook.cuh for the GLM-5.3-Flash routed experts
(quantization_config: exl3, bits=4, codebook=mcg, scope=glm53_routed_experts_only).

Storage per weight matrix (fixture: layers.3.mlp.experts.0.down_proj):
  trellis  int16 [k/16, n/16, 64]   64 uint16 = 1024 bits = 256 nibbles per 16x16 tile
  suh      fp16   [k]               per-row (k) scale+sign
  svh      fp16   [n]               per-col (n) scale+sign
  mcg      int32  [1]               codebook id (1 = mcg)

Reconstruction (reconstruct_had_slice):
  W = diag(suh) @ (H/8) @ What @ (H/8) @ diag(svh)
where H is the natural-order (Sylvester) 128 Hadamard and 1/8 = 1/sqrt(128)
(r_scale = 0.08838834764831845 in the kernel). What is the per-tile decoded
values placed by the mma fragment scatter (see tile_value_map below).

The decode of one 16-bit window (codebook.cuh decode_3inst, cb=1 = mcg):
  prod = (w16 * 0xCBAC1FED) mod 2^32
  y    = (prod & 0x8fff8fff) ^ 0x3b603b60        (lop3 0x6a = (a&b)^c)
  val  = fp16(y & 0xffff) + fp16(y >> 16)        (fp16 add)

Window j of a tile covers nibbles [4j, 4j+16) sliding by ONE nibble; there are
256 windows per tile, one weight each. Nibble m of the stream = bits
[4m, 4m+4) of the 64 uint16 words, LSB-first.
"""

import numpy as np

MAGIC = 0xCBAC1FED
AND_MASK = 0x8FFF8FFF
XOR_MASK = 0x3B603B60
R_SCALE = 0.08838834764831845  # 1/sqrt(128)


def decode_mcg(w16: np.ndarray) -> np.ndarray:
    """uint16 windows -> fp16 values (codebook.cuh decode_3inst, cb=1)."""
    w = w16.astype(np.uint32)
    prod = (w * np.uint32(MAGIC)) & np.uint32(0xFFFFFFFF)
    y = (prod & np.uint32(AND_MASK)) ^ np.uint32(XOR_MASK)
    lo = (y & np.uint32(0xFFFF)).astype(np.uint16)
    hi = (y >> np.uint32(16)).astype(np.uint16)
    flo = lo.view(np.float16) if lo.dtype.itemsize == 2 else lo.astype(np.uint16).view(np.float16)
    fhi = hi.view(np.float16) if hi.dtype.itemsize == 2 else hi.astype(np.uint16).view(np.float16)
    # fp16 add (kernel does __hadd2 in half precision)
    return (flo.astype(np.float32) + fhi.astype(np.float32)).astype(np.float16)



def hadamard128() -> np.ndarray:
    """Natural-order Sylvester H_128 (H[0] = all ones)."""
    H = np.ones((1, 1), dtype=np.float64)
    while H.shape[0] < 128:
        H = np.block([[H, H], [H, -H]])
    return H


def load_slot_composition(path=None):
    """Load the empirically-verified tile slot composition:
    slot (r,c) -> [(nibble_index, bit_position), ...4...].
    Generated by build_map.py + finalize_map.py against the exllamav3 oracle
    (probe-verified exact on random trellis, 3 seeds x 256 slots)."""
    import json, os
    p = path or os.path.join(os.path.dirname(os.path.abspath(__file__)),
                             "tile_slot_composition.json")
    raw = json.load(open(p))
    slots, idx, pos = [], [], []
    for k, v in sorted(raw.items(), key=lambda kv: tuple(int(x) for x in kv[0].split(","))):
        r, c = (int(x) for x in k.split(","))
        slots.append((r, c))
        idx.append([int(m) for m, _ in v])
        pos.append([int(p) for _, p in v])
    return (np.array(slots), np.array(idx, dtype=np.int64), np.array(pos, dtype=np.int64))


def dequant_exl3(trellis: np.ndarray, suh: np.ndarray, svh: np.ndarray) -> np.ndarray:
    """Full original-basis dequant. trellis uint16 [k/16, n/16, 64];
    suh fp16 [k]; svh fp16 [n]. Returns fp16 [k, n]."""
    kb, nb, words = trellis.shape
    assert words == 64
    k, n = kb * 16, nb * 16
    trellis = trellis.view(np.uint16) if trellis.dtype == np.int16 else trellis

    # nibble stream per tile: 64 uint16 -> 256 nibbles, LSB-first
    t = trellis.reshape(kb * nb, 64).astype(np.uint32)
    shifts = np.uint32(np.arange(16))
    bits = ((t[:, :, None] >> shifts) & np.uint32(1)).reshape(kb * nb, 1024).astype(np.uint8)
    nib = (bits[:, 0::4] << 0) | (bits[:, 1::4] << 1) | (bits[:, 2::4] << 2) | (bits[:, 3::4] << 3)

    slots, cidx, cpos = load_slot_composition()
    # compose each slot's 16-bit window from the verified (nibble, bitpos) map
    w16 = np.zeros((kb * nb, 256), dtype=np.uint32)
    for i in range(4):
        w16 |= nib[:, cidx[:, i]].astype(np.uint32) << np.uint32(4 * cpos[:, i])
    vals = decode_mcg(w16)                    # [kb*nb, 256] fp16

    what = np.zeros((k, n), dtype=np.float32)
    rows = np.array([s[0] for s in slots])
    cols = np.array([s[1] for s in slots])
    # tile (kb, nb) covers rows 16kb..16kb+15, cols 16nb..16nb+15
    rr = (np.arange(kb)[:, None, None] * 16 + rows[None, None, :])
    cc = (np.arange(nb)[None, :, None] * 16 + cols[None, None, :])
    what[rr, cc] = vals.reshape(kb, nb, 256)

    H = hadamard128()
    Hs = (H * R_SCALE).astype(np.float32)
    # Hadamard is per-128 block on BOTH dims: W[128i+a, 128j+b] = suh[a] (H What H)[a,b] svh[b]
    t2 = what.reshape(k // 128, 128, n // 128, 128)
    t2 = np.einsum("ab,ibjc,cd->ijad", Hs, t2, Hs)   # H symmetric
    t2 = t2.transpose(0, 2, 1, 3)                    # (i,a,j,d) -> row=i*128+a, col=j*128+d
    w = t2.reshape(k, n) * suh[:, None].astype(np.float32) * svh[None, :].astype(np.float32)
    return w.astype(np.float16)


def load_fixture(fixture_dir: str, proj: str = "down_proj") -> dict:
    """Load the extracted fixture tensors for one expert projection."""
    import os
    pre = f"layers_3_mlp_experts_0_{proj}_"
    if proj == "down_proj":
        shapes = {"trellis": (128, 256, 64), "suh": (2048,), "svh": (4096,), "mcg": (1,)}
    else:
        shapes = {"trellis": (256, 128, 64), "suh": (4096,), "svh": (2048,), "mcg": (1,)}
    out = {}
    for name, dt in (("trellis", "<i2"), ("suh", "<f2"), ("svh", "<f2"), ("mcg", "<i4")):
        p = os.path.join(fixture_dir, pre + name + ".bin")
        with open(p, "rb") as f:
            raw = f.read()
        out[name] = np.frombuffer(raw, dtype=dt).reshape(shapes[name])
    return out



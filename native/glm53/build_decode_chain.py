# ---------------------------------------------------------------- moe_tail_step
w('''# ============================================================ phase-2 MoE tail (one token)
# tail_site's body for R = 1, with the map body passed in (no re-read per layer) and
# no file writes. Resolves the hc_ffn triple + post LN from `gt` (the caller's layer
# GxLoc, KDA-MoE want-list order), the router and shared expert by their own small
# resolves, and each USED expert lazily by 9 names (the drift-safe per-expert form).
moe_tail_step(streams1<Vec<Float>>, lpre<String>, dir<String>, total<Int>, idxtext<String>, mapbody<String>,
              gt<GxLoc>, fgemm<Int>, fbf<Int>, fdeq<Int>, fhgen<Int>, fhad1<Int>, fhad2<Int>)<Vec<Float>> -> {
    nonev<Vec<Float>> = Vec()
    best<Int> = 0
    bestv<Float> = 0.0
    cv<Float> = 0.0
    d2<Int> = 0
    d_flat2<Int> = 0
    d_mv2<Int> = 0
    d_scr2<Int> = 0
    dup<Int> = 0
    e<Int> = 0
    epre<String> = ""
    g1<Float> = 0.0
    i<Int> = 0
    j<Int> = 0
    k<Int> = 0
    lane<Int> = 0
    nex<Int> = 0
    nfound<Int> = 0
    nt<Int> = 0
    r<Int> = 0
    raw_bias<String> = ""
    sm<Float> = 0.0
    tix<Int> = 0
    tk<Int> = 0
    u1<Float> = 0.0
    wt<Float> = 0.0
    i0<Int> = 0
    d_fnF<Int> = 0
    d_ln2<Int> = 0
    body<String> = mapbody

    d_fnF = deq_bf16(fbf, gx_read(gt, 17), 24 * HC * H, HC * H)
    if (d_fnF == 0) { return nonev }
    baseF<Vec<Float>> = Vec()
    raw_baseF<String> = gx_read(gt, 18)
    j = 0
    while (j < 24) {
        baseF.push(f32_at(raw_baseF, j))
        j = j + 1
    }
    scaleF<Vec<Float>> = Vec()
    raw_scaleF<String> = gx_read(gt, 19)
    j = 0
    while (j < 3) {
        scaleF.push(f32_at(raw_scaleF, j))
        j = j + 1
    }
    d_ln2 = deq_bf16(fbf, gx_read(gt, 13), H, 0)
    if (d_ln2 == 0) { return nonev }
    post_ln<Vec<Float>> = bulk_dtoh(d_ln2, H)
    free_dev(d_ln2)

    flat<Vec<Float>> = rms_rows(streams1, R, HC * H, Vec())
    d_flat2 = alloc_dev(R * HC * H * 8)
    d_mv2 = alloc_dev(R * 24 * 8)
    d_scr2 = alloc_dev(64)
    if (d_flat2 == 0 || d_mv2 == 0 || d_scr2 == 0) { return nonev }
    bulk_htod(d_flat2, view(flat))
    if (gemm(fgemm, d_scr2, d_flat2, d_fnF, d_mv2, R, 24, HC * H, 1.0, 0.0) != 0) { return nonev }
    sync()
    mv2<Vec<Float>> = bulk_dtoh(d_mv2, R * 24)
    free_dev(d_flat2)
    free_dev(d_mv2)
    free_dev(d_scr2)
    free_dev(d_fnF)

    res2<Vec<Float>> = hc_glue(mv2, baseF, scaleF, streams1)
    collapsed2<Vec<Float>> = Vec()
    i = 0
    while (i < R * H) {
        collapsed2.push(res2.get(i))
        i = i + 1
    }
    post2<Vec<Float>> = Vec()
    i = 0
    while (i < R * HC) {
        post2.push(res2.get(R * H + i))
        i = i + 1
    }
    comb2<Vec<Float>> = Vec()
    i = 0
    while (i < R * HC * HC) {
        comb2.push(res2.get(R * H + R * HC + i))
        i = i + 1
    }
    h2<Vec<Float>> = rms_rows(collapsed2, R, H, post_ln)

    # ---- router (same code path as L3_MOE_ROUTE_VYB) ----
    want<Vec<String>> = Vec()
    want.push(lpre + "mlp.gate.weight")
    want.push(lpre + "mlp.gate.e_score_correction_bias")
    g<GxLoc> = gx_resolve_idx(idxtext, dir, total, want)
    d_gw<Int> = deq_bf16(fbf, gx_read(g, 0), NE * H, H)
    if (d_gw == 0) { return nonev }
    logits<Vec<Float>> = mm_host(h2, R, H, d_gw, NE, fgemm)
    freedom {
        cuMemFree_v2(d_gw)
    }
    raw_bias = gx_read(g, 1)
    bias<Vec<Float>> = Vec()
    i = 0
    while (i < NE) {
        bias.push(f32_at(raw_bias, i))
        i = i + 1
    }
    scores<Vec<Float>> = Vec()
    i = 0
    while (i < logits.len()) {
        scores.push(sigmoid(logits.get(i)))
        i = i + 1
    }

    # top-8 per token + renormed weights
    rsel<Vec<Int>> = Vec()        # [R, 8]
    rwt<Vec<Float>> = Vec()       # [R, 8]
    i = 0
    while (i < R * ROUTE_TOPK) {
        rsel.push(-1)
        rwt.push(0.0)
        i = i + 1
    }
    r = 0
    while (r < R) {
        lane = 0
        while (lane < ROUTE_TOPK) {
            best = -1
            bestv = 0.0 - 1e30
            j = 0
            while (j < NE) {
                dup = 0
                k = 0
                while (k < lane) {
                    if (rsel.get(r * ROUTE_TOPK + k) == j) { dup = 1 }
                    k = k + 1
                }
                if (dup == 0) {
                    cv = scores.get(r * NE + j) + bias.get(j)
                    if (cv > bestv) {
                        bestv = cv
                        best = j
                    }
                }
                j = j + 1
            }
            rsel.set(r * ROUTE_TOPK + lane, best)
            lane = lane + 1
        }
        sm = 0.0
        lane = 0
        while (lane < ROUTE_TOPK) {
            sm = sm + scores.get(r * NE + rsel.get(r * ROUTE_TOPK + lane))
            lane = lane + 1
        }
        lane = 0
        while (lane < ROUTE_TOPK) {
            rwt.set(r * ROUTE_TOPK + lane,
                    scores.get(r * NE + rsel.get(r * ROUTE_TOPK + lane)) / (sm + 1e-20) * ROUTED_SCALE)
            lane = lane + 1
        }
        r = r + 1
    }

    # ---- routed experts: one dequant per (expert, projection), FFN on that expert's tokens
    accr<Vec<Float>> = Vec()
    i = 0
    while (i < R * H) {
        accr.push(0.0)
        i = i + 1
    }
    nex = 0
    e = 0
    while (e < NE) {
        toks<Vec<Int>> = Vec()
        lanes<Vec<Int>> = Vec()
        r = 0
        while (r < R) {
            lane = 0
            while (lane < ROUTE_TOPK) {
                if (rsel.get(r * ROUTE_TOPK + lane) == e) {
                    toks.push(r)
                    lanes.push(lane)
                }
                lane = lane + 1
            }
            r = r + 1
        }
        nt = toks.len()
        if (nt > 0) {
            nex = nex + 1
            epre = lpre + "mlp.experts." + e.to_string() + "."
            w2<Vec<String>> = Vec()
            w2.push(epre + "gate_proj.trellis")
            w2.push(epre + "gate_proj.suh")
            w2.push(epre + "gate_proj.svh")
            w2.push(epre + "up_proj.trellis")
            w2.push(epre + "up_proj.suh")
            w2.push(epre + "up_proj.svh")
            w2.push(epre + "down_proj.trellis")
            w2.push(epre + "down_proj.suh")
            w2.push(epre + "down_proj.svh")
            ge<GxLoc> = gx_resolve_idx(idxtext, dir, total, w2)
            nfound = 0
            j = 0
            while (j < w2.len()) {
                if (ge.found.get(j) == 1) { nfound = nfound + 1 }
                j = j + 1
            }
            if (nfound != w2.len()) { println("CHAIN_FAIL resolve expert " + e.to_string()); return nonev }

            dWg<Int> = exl3_deq(fdeq, fhgen, fhad1, fhad2, gx_read(ge, 0), gx_read(ge, 1),
                                gx_read(ge, 2), body, EINTER, 32768)
            dWu<Int> = exl3_deq(fdeq, fhgen, fhad1, fhad2, gx_read(ge, 3), gx_read(ge, 4),
                                gx_read(ge, 5), body, EINTER, 32768)
            dWd<Int> = exl3_deq(fdeq, fhgen, fhad1, fhad2, gx_read(ge, 6), gx_read(ge, 7),
                                gx_read(ge, 8), body, H, 32768)
            if (dWg == 0 || dWu == 0 || dWd == 0) {
                println("CHAIN_FAIL deq expert " + e.to_string())
                return nonev
            }

            sub<Vec<Float>> = Vec()
            j = 0
            while (j < nt) {
                tix = toks.get(j) * H
                d2 = 0
                while (d2 < H) {
                    sub.push(h2.get(tix + d2))
                    d2 = d2 + 1
                }
                j = j + 1
            }
            gv<Vec<Float>> = mm_host(sub, nt, H, dWg, EINTER, fgemm)
            uv<Vec<Float>> = mm_host(sub, nt, H, dWu, EINTER, fgemm)
            act<Vec<Float>> = Vec()
            j = 0
            while (j < gv.len()) {
                g1 = gv.get(j)
                if (g1 > SWIGLU_LIMIT) { g1 = SWIGLU_LIMIT }
                u1 = uv.get(j)
                if (u1 > SWIGLU_LIMIT) { u1 = SWIGLU_LIMIT }
                if (u1 < 0.0 - SWIGLU_LIMIT) { u1 = 0.0 - SWIGLU_LIMIT }
                act.push(silu(g1) * u1)
                j = j + 1
            }
            yv<Vec<Float>> = mm_host(act, nt, EINTER, dWd, H, fgemm)
            j = 0
            while (j < nt) {
                tk = toks.get(j)
                wt = rwt.get(tk * ROUTE_TOPK + lanes.get(j))
                d2 = 0
                while (d2 < H) {
                    accr.set(tk * H + d2, accr.get(tk * H + d2) + wt * yv.get(j * H + d2))
                    d2 = d2 + 1
                }
                j = j + 1
            }
            freedom {
                cuMemFree_v2(dWg)
                cuMemFree_v2(dWu)
                cuMemFree_v2(dWd)
            }
        }
        e = e + 1
    }
    println("  routed experts used: " + nex.to_string())

    # ---- shared expert ----
    w3<Vec<String>> = Vec()
    w3.push(lpre + "mlp.shared_experts.gate_proj.weight")
    w3.push(lpre + "mlp.shared_experts.up_proj.weight")
    w3.push(lpre + "mlp.shared_experts.down_proj.weight")
    gs<GxLoc> = gx_resolve_idx(idxtext, dir, total, w3)
    d_sg<Int> = deq_bf16(fbf, gx_read(gs, 0), EINTER * H, H)
    d_su<Int> = deq_bf16(fbf, gx_read(gs, 1), EINTER * H, H)
    d_sd<Int> = deq_bf16(fbf, gx_read(gs, 2), H * EINTER, EINTER)
    if (d_sg == 0 || d_su == 0 || d_sd == 0) { return nonev }
    sgate<Vec<Float>> = mm_host(h2, R, H, d_sg, EINTER, fgemm)
    sup<Vec<Float>> = mm_host(h2, R, H, d_su, EINTER, fgemm)
    sact<Vec<Float>> = Vec()
    i = 0
    while (i < sgate.len()) {
        g1 = sgate.get(i)
        if (g1 > SWIGLU_LIMIT) { g1 = SWIGLU_LIMIT }
        u1 = sup.get(i)
        if (u1 > SWIGLU_LIMIT) { u1 = SWIGLU_LIMIT }
        if (u1 < 0.0 - SWIGLU_LIMIT) { u1 = 0.0 - SWIGLU_LIMIT }
        sact.push(silu(g1) * u1)
        i = i + 1
    }
    shared<Vec<Float>> = mm_host(sact, R, EINTER, d_sd, H, fgemm)
    freedom {
        cuMemFree_v2(d_sg)
        cuMemFree_v2(d_su)
        cuMemFree_v2(d_sd)
    }

    mlp<Vec<Float>> = Vec()
    i = 0
    while (i < R * H) {
        mlp.push(accr.get(i) + shared.get(i))
        i = i + 1
    }

    streams2<Vec<Float>> = hc_apply(streams1, mlp, post2, comb2)
    return streams2
}
''')


# Generates rgemv6.vyb: llama.cpp-style lane map for the Ridge IQ2_S / IQ3_S decode GEMVs
# (gemv_iq2s_m / gemv_iq3s_m), opt-in via VYB_RGMAP=1. NOT bit-identical to rgemv5: each lane owns one
# 32-weight sub-block (ib32) of a super-block, 8 lanes per super-block, so a warp covers 4 super-blocks
# (328 B of IQ2_S / 440 B of IQ3_S per row) per trip with 16-bit raw loads; per-lane f32 partial sums
# then the same shfl_down_f64 tree. Derived from llama.cpp vec_dot_iq2_s_q8_1 / vec_dot_iq3_s_q8_1 (MIT).
# usage: gen_rgemv6.py out.vyb [TPB] [U]   (U = super-block trips unrolled per loop iteration, 1 or 2)
# Launch ceil(N/(TPB/32)) blocks x TPB, 1 row per warp; compile with --kernel-shared 8192.
import sys
OUTF = sys.argv[1] if len(sys.argv) > 1 else "rgemv6.vyb"
TPB = int(sys.argv[2]) if len(sys.argv) > 2 else 512
U = int(sys.argv[3]) if len(sys.argv) > 3 else 1
WPR = int(sys.argv[5]) if len(sys.argv) > 5 else 1   # warps per row (cross-warp sum through shared memory)
RB = TPB // 32 // WPR
PERM = int(sys.argv[7]) if len(sys.argv) > 7 else 1   # 1: x read from the xperm6-permuted copy (coalesced 512 B per load instruction)
SMG = int(sys.argv[6]) if len(sys.argv) > 6 else 1   # 1: IQ grid copied to shared per block; 0: read through L1
out = []
w = out.append
w(f"""// GENERATED by gen_rgemv6.py (TPB={TPB}, U={U}). Ridge IQ decode GEMVs, llama.cpp-style lane map
// (one ib32 per lane, 4 super-blocks per warp trip). Opt-in VYB_RGMAP=1; not bit-identical to rgemv5.
""")

def hdr(name, gb):
    w(f"""{name}(p<Int>) -> {{
    W<Int> = ld_i64(p + 0)
    X<Int> = ld_i64(p + 8)
    Y<Int> = ld_i64(p + 16)
    N<Int> = ld_i64(p + 32)
    K<Int> = ld_i64(p + 40)
    YE<Int> = ld_i64(p + 48)
    RS<Int> = ld_i64(p + 120)
    G<Int> = ld_i64(p + 128)
    tid<Int> = tid_x()
    l<Int> = tid % 32
    n0<Int> = blk_x() * {RB} + (tid / 32) / {WPR}
    ws<Int> = (tid / 32) % {WPR}
    nsb<Int> = K / 256
    c1<Float32> = 1.0 as Float32
    c2<Float32> = 2.0 as Float32
    ch<Float32> = 0.5 as Float32
    cq<Float32> = 0.25 as Float32
    acc<Float32> = 0.0
    mg<UInt32> = 1258291200 as UInt32
    mgf<Float32> = 8388608.0 as Float32""")
    for c in (range(0, gb // 16, TPB) if SMG else []):
        w(f"""    if (tid + {c} < {gb // 16}) {{
        st_shared_v4_u32((tid + {c}) * 16, ld_v4_u32(G + (tid + {c}) * 16, 0), ld_v4_u32(G + (tid + {c}) * 16, 1), ld_v4_u32(G + (tid + {c}) * 16, 2), ld_v4_u32(G + (tid + {c}) * 16, 3))
    }}""")
    if SMG:
        w("    kernel_barrier()")
    w("    ib<Int> = l % 8")

def tail():
    if WPR > 1:
        w(f"""    s<Float> = acc as Float
    s = s + shfl_down_f64(s, 16)
    s = s + shfl_down_f64(s, 8)
    s = s + shfl_down_f64(s, 4)
    s = s + shfl_down_f64(s, 2)
    s = s + shfl_down_f64(s, 1)
    if (l == 0) {{ st_shared_f64(1024 + tid / 32, s) }}
    kernel_barrier()
    if (n0 < N) {{
        if (l == 0) {{
            if (ws == 0) {{""")
        w("                t<Float> = s")
        for q in range(1, WPR):
            w(f"                t = t + ld_shared_f64(1024 + tid / 32 + {q})")
        w("""                if (YE == 4) { st_f32(Y + n0 * 4, t as Float32) } else {
                    if (RS != 0) { t = ld_f64(RS + n0 * 8) + t }
                    st_f64(Y + n0 * 8, t)
                }
            }
        }
    }
}
""")
        return
    w("""    if (n0 < N) {
        s<Float> = acc as Float
        s = s + shfl_down_f64(s, 16)
        s = s + shfl_down_f64(s, 8)
        s = s + shfl_down_f64(s, 4)
        s = s + shfl_down_f64(s, 2)
        s = s + shfl_down_f64(s, 1)
        if (l == 0) {
            if (YE == 4) { st_f32(Y + n0 * 4, s as Float32) } else {
                if (RS != 0) { s = ld_f64(RS + n0 * 8) + s }
                st_f64(Y + n0 * 8, s)
            }
        }
    }
}
""")

def xl(ind, u):
    for e in range(32):
        st = 512 * (e // 4) if PERM else 16 * (e // 4)
        w(f"{ind}x{u}_{e}<Float32> = ld_v4_f32(xb{u} + {st}, {e%4})")

MAG = int(sys.argv[4]) if len(sys.argv) > 4 else 1   # 1: byte->f32 via the 2^23 magic OR/sub and the sign as an f32 sign-bit xor on x (both exact)
def grp8(ind, u, k, gsrc0, gsrc1, sgexpr, sh0, sh1):
    if MAG:
        for e in range(8):
            src = gsrc0 if e < 4 else gsrc1
            sh = "" if e % 4 == 0 else f" >> {8*(e%4)}"
            sgs = f"(({sgexpr} >> {e}) & 1) << 31" if e else f"({sgexpr} & 1) << 31"
            w(f"{ind}w{u}_{k}_{e}<Float32> = f32_from_bits((({src}{sh}) & 255) | mg) - mgf")
            w(f"{ind}v{u}_{k}_{e}<Float32> = f32_from_bits(f32_bits(x{u}_{8*k+e}) ^ ({sgs}))")
        w(f"{ind}pt{u}_{k}<Float32> = v{u}_{k}_0 * w{u}_{k}_0")
        for e in range(1, 8):
            w(f"{ind}pt{u}_{k} = pt{u}_{k} + v{u}_{k}_{e} * w{u}_{k}_{e}")
        return
    # 8 weights: grid bytes from gsrc0 (e<4) / gsrc1 (e>=4), sign bits from sgexpr
    for e in range(8):
        src = gsrc0 if e < 4 else gsrc1
        sh = "" if e % 4 == 0 else f" >> {8*(e%4)}"
        sb_ = f"({sgexpr} & 1)" if e == 0 else f"(({sgexpr} >> {e}) & 1)"
        w(f"{ind}w{u}_{k}_{e}<Float32> = ((({src}{sh}) & 255) as Float32) * (c1 - c2 * ({sb_} as Float32))")
    w(f"{ind}pt{u}_{k}<Float32> = x{u}_{8*k} * w{u}_{k}_0")
    for e in range(1, 8):
        w(f"{ind}pt{u}_{k} = pt{u}_{k} + x{u}_{8*k+e} * w{u}_{k}_{e}")

def iq2(ind, u):
    w(f"{ind}d{u}<Float32> = ld_f16(bb{u})")
    w(f"{ind}q01_{u}<Int> = (ld_u16(bb{u} + 2 + 4 * ib) as Int) & 65535")
    w(f"{ind}q23_{u}<Int> = (ld_u16(bb{u} + 4 + 4 * ib) as Int) & 65535")
    w(f"{ind}s01_{u}<Int> = (ld_u16(bb{u} + 34 + 4 * ib) as Int) & 65535")
    w(f"{ind}s23_{u}<Int> = (ld_u16(bb{u} + 36 + 4 * ib) as Int) & 65535")
    w(f"{ind}qh{u}<Int> = (ld_i8(bb{u} + 66 + ib) as Int) & 255")
    w(f"{ind}sc{u}<Int> = (ld_i8(bb{u} + 74 + ib) as Int) & 255")
    xl(ind, u)
    for k in range(4):
        qv = f"q01_{u}" if k < 2 else f"q23_{u}"
        sv = f"s01_{u}" if k < 2 else f"s23_{u}"
        sh = "" if k % 2 == 0 else " >> 8"
        w(f"{ind}ix{u}_{k}<Int> = (({qv}{sh}) & 255) | ((qh{u} << {8 - 2*k}) & 768)")
        if SMG:
            w(f"{ind}ga{u}_{k}<UInt32> = ld_shared_v2_u32(ix{u}_{k} * 8, 0)")
            w(f"{ind}gb{u}_{k}<UInt32> = ld_shared_v2_u32(ix{u}_{k} * 8, 1)")
        else:
            w(f"{ind}ga{u}_{k}<UInt32> = ld_i32(G + ix{u}_{k} * 8) as UInt32")
            w(f"{ind}gb{u}_{k}<UInt32> = ld_i32(G + ix{u}_{k} * 8 + 4) as UInt32")
        w(f"{ind}sg{u}_{k}<UInt32> = (({sv}{sh}) & 255) as UInt32")
        grp8(ind, u, k, f"ga{u}_{k}", f"gb{u}_{k}", f"sg{u}_{k}", 0, 0)
    w(f"{ind}dlo{u}<Float32> = d{u} * (((sc{u} & 15) as Float32) + ch) * cq")
    w(f"{ind}dhi{u}<Float32> = d{u} * ((((sc{u} >> 4) & 15) as Float32) + ch) * cq")
    w(f"{ind}acc = acc + dlo{u} * (pt{u}_0 + pt{u}_1) + dhi{u} * (pt{u}_2 + pt{u}_3)")

def iq3(ind, u):
    w(f"{ind}d{u}<Float32> = ld_f16(bb{u})")
    for k in range(4):
        w(f"{ind}qw{u}_{k}<Int> = (ld_u16(bb{u} + 2 + 8 * ib + {2*k}) as Int) & 65535")
    w(f"{ind}qh{u}<Int> = (ld_i8(bb{u} + 66 + ib) as Int) & 255")
    w(f"{ind}s01_{u}<Int> = (ld_u16(bb{u} + 74 + 4 * ib) as Int) & 65535")
    w(f"{ind}s23_{u}<Int> = (ld_u16(bb{u} + 76 + 4 * ib) as Int) & 65535")
    w(f"{ind}sc{u}<Int> = (ld_i8(bb{u} + 106 + ib / 2) as Int) & 255")
    xl(ind, u)
    for k in range(4):
        sv = f"s01_{u}" if k < 2 else f"s23_{u}"
        sh = "" if k % 2 == 0 else " >> 8"
        w(f"{ind}i1_{u}_{k}<Int> = (qw{u}_{k} & 255) | ((qh{u} << {8 - 2*k}) & 256)")
        w(f"{ind}i2_{u}_{k}<Int> = (qw{u}_{k} >> 8) | ((qh{u} << {7 - 2*k}) & 256)")
        if SMG:
            w(f"{ind}ga{u}_{k}<UInt32> = ld_shared_u32(i1_{u}_{k} * 4)")
            w(f"{ind}gb{u}_{k}<UInt32> = ld_shared_u32(i2_{u}_{k} * 4)")
        else:
            w(f"{ind}ga{u}_{k}<UInt32> = ld_i32(G + i1_{u}_{k} * 4) as UInt32")
            w(f"{ind}gb{u}_{k}<UInt32> = ld_i32(G + i2_{u}_{k} * 4) as UInt32")
        w(f"{ind}sg{u}_{k}<UInt32> = (({sv}{sh}) & 255) as UInt32")
        grp8(ind, u, k, f"ga{u}_{k}", f"gb{u}_{k}", f"sg{u}_{k}", 0, 0)
    w(f"{ind}db{u}<Float32> = d{u} * (c1 + c2 * (((sc{u} >> (4 * (ib % 2))) & 15) as Float32))")
    w(f"{ind}acc = acc + db{u} * (pt{u}_0 + pt{u}_1 + pt{u}_2 + pt{u}_3)")

def kern(name, bs, gb, body):
    hdr(name, gb)
    w(f"""    if (n0 < N) {{
        rb<Int> = W + n0 * (nsb * {bs})
        sb<Int> = ws * 4 + l / 8
        while (sb < nsb) {{""")
    I = "            "
    for u in range(U):
        su = f"sb + {4*u}" if u else "sb"
        if u:
            w(f"{I}if ({su} < nsb) {{")
        ind = I + ("    " if u else "")
        w(f"{ind}bb{u}<Int> = rb + ({su}) * {bs}")
        if PERM:
            w(f"{ind}xb{u}<Int> = X + (({su}) - l / 8) * 1024 + l * 16")
        else:
            w(f"{ind}xb{u}<Int> = X + (({su}) * 256 + ib * 32) * 4")
        body(ind, u)
        if u:
            w(f"{I}}}")
    w(f"{I}sb = sb + {4*U*WPR}")
    w("        }")
    w("    }")
    tail()

kern("gemv_iq2s_m", 82, 8192, iq2)
kern("gemv_iq3s_m", 110, 2048, iq3)
w("""
// x permute for gemv_*_m (PERM=1, WPR=1, U=1): Y[t*1024 + v*128 + L*4 + c] = X[t*1024 + (L/8)*256 + (L%8)*32 + v*4 + c]
// so each of the 8 per-lane ld_v4_f32 x loads is one coalesced 512 B warp access. K % 1024 == 0. +0 X +8 Y +16 K. Grid ceil(K/256) x 256.
xperm6(p<Int>) -> {
    X<Int> = ld_i64(p + 0)
    Y<Int> = ld_i64(p + 8)
    K<Int> = ld_i64(p + 16)
    i<Int> = blk_x() * 256 + tid_x()
    if (i < K) {
        t<Int> = i / 1024
        r<Int> = i % 1024
        v<Int> = r / 128
        L<Int> = (r % 128) / 4
        c<Int> = r % 4
        st_f32(Y + i * 4, ld_f32(X + (t * 1024 + (L / 8) * 256 + (L % 8) * 32 + v * 4 + c) * 4))
    }
}
""")
open(OUTF, "w").write("\n".join(out))

# Generates rq6k8.vyb: Ridge Q6_K decode GEMV gemv_q6k_v with the rgemv8 weight-read restructure. Same lane map,
# per-lane arithmetic and reduction as gen_rq6k.py 1 2 (rq6k.vyb) -> bit-identical; the row is streamed CH super-
# blocks (CH*210 B) at a time as coalesced u32 loads (word i in lane i%32, register i/32), PD+1 chunks in flight,
# and each lane's ql/qh u16s, signed scale bytes and the f16 d come out of those registers by shfl_idx_u32.
# Only registers a field can touch (lane offsets known at generation time) are shuffled. Needs K/256 % CH == 0.
# usage: gen_rq6k8.py out.vyb CH PD
import sys
OUTF = sys.argv[1] if len(sys.argv) > 1 else "rq6k8.vyb"
CH = int(sys.argv[2]) if len(sys.argv) > 2 else 2
PD = int(sys.argv[3]) if len(sys.argv) > 3 else 1
SB = 210
assert (CH * SB) % 4 == 0
NW = CH * SB // 4
NR = (NW + 31) // 32
out = []
w = out.append
src = open("kernels/rq6k.vyb").read().split("\n")
# header up to (excluding) the "if (n0 < N) {" compute block: params + multi-segment select + constants
hi = [i for i, s in enumerate(src) if s.strip() == "acc0<Float32> = 0.0"][0]
w(f"// GENERATED by gen_rq6k8.py (CH={CH}, PD={PD}). Ridge Q6_K decode GEMV: coalesced u32 row stream + shfl_idx")
w("// extract; bit-identical to rq6k.vyb (gen_rq6k.py 1 2) / qwen3 gemv_q6k (M=1). Derived from llama.cpp (MIT).")
w("\n".join(src[1:hi + 1]))
w(f"""    if (n0 < N) {{
        xr<Int> = X + (g * 128 + jj) * 4
        rb0<Int> = W + (n0 + 0) * nsb * 210
        nch<Int> = nsb / {CH}""")
def ldc(pref, cexpr, decl, ind):
    for r in range(NR):
        last = (r == NR - 1) and (NW % 32 != 0)
        if decl:
            w(f"{ind}{pref}{r}<UInt32> = 0 as UInt32")
        ld = f"{pref}{r} = ld_u32(rb0 + ({cexpr}) * {CH * SB} + {r * 128} + l * 4)"
        w(f"{ind}if (l < {NW % 32}) {{ {ld} }}" if last else f"{ind}{ld}")
for d in range(PD + 1):
    w(f"        cp{d}<Int> = {d}")
    w(f"        if (cp{d} >= nch) {{ cp{d} = nch - 1 }}")
    ldc(f"q{d}_", f"cp{d}", True, "        ")
w("""        c<Int> = 0
        while (c < nch) {""")
for r in range(NR):
    w(f"            u{r}<UInt32> = q0_{r}")
for d in range(PD):
    for r in range(NR):
        w(f"            q{d}_{r} = q{d + 1}_{r}")
w(f"""            cn<Int> = c + {PD + 1}
            if (cn >= nch) {{ cn = nch - 1 }}""")
ldc(f"q{PD}_", "cn", False, "            ")
def lanes(fn):
    return [fn(l) for l in range(32)]
def fetch(name, offs, expr, mask):
    regs = sorted(set((o // 4) // 32 for o in offs))
    w(f"            o{name}<Int> = {expr}")
    w(f"            s{name}<Int> = (o{name} / 4) % 32")
    w(f"            v{name}<UInt32> = shfl_idx_u32(u{regs[0]}, s{name})")
    for r in regs[1:]:
        w(f"            t{name}_{r}<UInt32> = shfl_idx_u32(u{r}, s{name})")
        w(f"            if ((o{name} / 4) / 32 == {r}) {{ v{name} = t{name}_{r} }}")
    w(f"            b{name}<UInt32> = (v{name} >> (((o{name} % 4) * 8) as UInt32)) & {mask}")
G = lambda l: l // 16
JJ = lambda l: (l % 16) * 2
for j in range(CH):
    b = j * SB
    od = b + 208
    w(f"            sb{j}<Int> = c * {CH} + {j}")
    w(f"            xq{j}<Int> = xr + sb{j} * 1024")
    for q, xo in enumerate([0, 128, 256, 384, 4, 132, 260, 388]):
        w(f"            xv{q}_{j}<Float32> = ld_f32(xq{j} + {xo})")
    w(f"            dw{j}<UInt32> = shfl_idx_u32(u{(od // 4) // 32}, {(od // 4) % 32})")
    w(f"            df{j}<Float32> = {'h_lo' if od % 4 == 0 else 'h_hi'}(dw{j})")
    for k in range(4):
        fetch(f"s{k}_{j}", lanes(lambda l: b + 192 + G(l) * 8 + JJ(l) // 16 + 2 * k), f"{b + 192 + 2 * k} + g8is", 255)
        w(f"            s{k}{j}<Int32> = (((bs{k}_{j} as Int) ^ 128) - 128) as Int32")
    fetch(f"qa{j}", lanes(lambda l: b + G(l) * 64 + JJ(l)), f"{b} + g64jj", 65535)
    fetch(f"qb{j}", lanes(lambda l: b + G(l) * 64 + JJ(l) + 32), f"{b + 32} + g64jj", 65535)
    fetch(f"qh{j}", lanes(lambda l: b + 128 + G(l) * 32 + JJ(l)), f"{b + 128} + g32jj", 65535)
    w(f"""            qa{j}<UInt32> = bqa{j}
            qb{j}<UInt32> = bqb{j}
            qh{j}<UInt32> = bqh{j}
            da{j}<Float32> = df{j} * (s0{j} as Float32)
            db{j}<Float32> = df{j} * (s1{j} as Float32)
            dc{j}<Float32> = df{j} * (s2{j} as Float32)
            dd{j}<Float32> = df{j} * (s3{j} as Float32)""")
    for k, (qq, sa, sh) in enumerate([("qa", 0, 0), ("qb", 0, 2), ("qa", 4, 4), ("qb", 4, 6)], 1):
        w(f"            v{k}_{j}<Float32> = (((({qq}{j} >> {sa}) & 3855) | ((({'qh'}{j} >> {sh}) & 771) << 4)) as Float32)")
        w(f"            h{k}_{j}<Float32> = (v{k}_{j} * c8 + cmg) - cmg")
        w(f"            l{k}_{j}<Float32> = v{k}_{j} - h{k}_{j} * c256")
    for q, (dn, hl, k) in enumerate([("da", "l", 1), ("db", "l", 2), ("dc", "l", 3), ("dd", "l", 4), ("da", "h", 1), ("db", "h", 2), ("dc", "h", 3), ("dd", "h", 4)]):
        w(f"            acc0 = acc0 + xv{q}_{j} * ({dn}{j} * ({hl}{k}_{j} - c32))")
w("            c = c + 1\n        }")
ti = [i for i, s in enumerate(src) if s.strip() == "s0<Float> = acc0 as Float"][0]
w("\n".join(src[ti:]))
open("kernels/" + OUTF, "w").write("\n".join(out))

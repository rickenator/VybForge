# Generates rq4k.vyb: Ridge Q4_K decode GEMV gemv_q4k_v (M = 1). Same lane map and per-lane arithmetic
# as qwen3.vyb gemv_q4k (so bit-identical), with ld_v4_f32 x loads, a D-deep super-block prefetch ring,
# R rows per warp and a shfl_down_f64 reduction (same 16,8,4,2,1 pairing as the shared-memory tree).
# Same params as gemv_q4k incl. the 3 fused row segments (@56.., @88..) and RS residual (@120).
# Launch ceil(Ntot/(16*R)) x 512 where Ntot = N + N2 + N3 (each segment's N a multiple of R).
# usage: gen_rq4k.py R D out.vyb
import sys
R = int(sys.argv[1]); D = int(sys.argv[2]); OUTF = sys.argv[3]
out = []; w = out.append
w(f"""// GENERATED by gen_rq4k.py (R={R}, D={D}). Ridge Q4_K decode GEMV; see the generator header.
// Q4_K decode from ggml-quants.c (MIT, see THIRD-PARTY.md) via qwen3.vyb gemv_q4k.

gemv_q4k_v(p<Int>) -> {{
    W<Int> = ld_i64(p + 0)
    X<Int> = ld_i64(p + 8)
    Y<Int> = ld_i64(p + 16)
    N<Int> = ld_i64(p + 32)
    K<Int> = ld_i64(p + 40)
    YE<Int> = ld_i64(p + 48)
    tid<Int> = tid_x()
    l<Int> = tid % 32
    n0<Int> = (blk_x() * 16 + tid / 32) * {R}
    NS2<Int> = ld_i64(p + 64)
    RS<Int> = ld_i64(p + 120)
    NS3<Int> = ld_i64(p + 96)
    if (n0 >= N) {{
        if (n0 < N + NS2) {{
            n0 = n0 - N
            W = ld_i64(p + 56)
            Y = ld_i64(p + 72)
            YE = ld_i64(p + 80)
            N = NS2
        }} else {{
            n0 = n0 - N - NS2
            W = ld_i64(p + 88)
            Y = ld_i64(p + 104)
            YE = ld_i64(p + 112)
            N = NS3
        }}
    }}
    nsb<Int> = K / 256
    c16<Float32> = 0.0000152587890625 as Float32
    c65<Float32> = 65536.0 as Float32
    cmg<Float32> = 12582912.0 as Float32
    t<Int> = l / 8
    l4<Int> = l * 4
    sh<UInt32> = ((t % 2) * 16) as UInt32
    mk<UInt32> = (0 as UInt32) - ((t / 2) as UInt32)
    nmk<UInt32> = (0 as UInt32) - ((1 - t / 2) as UInt32)""")
for r in range(R):
    w(f"    acc{r}<Float32> = 0.0")
w("    if (n0 < N) {")
w("        xr<Int> = X + ((l / 8) * 64 + (l % 8) * 4) * 4")
for r in range(R):
    w(f"        rb{r}<Int> = W + (n0 + {r}) * nsb * 144")
    if r > 0:
        w(f"        if (n0 + {r} >= N) {{ rb{r} = rb0 }}")
RAW = [("df", "Float32", "ld_f16({b})"), ("mnf", "Float32", "ld_f16({b} + 2)"),
       ("ba", "UInt32", "ld_u32({b} + 4)"), ("bc", "UInt32", "ld_u32({b} + 8)"),
       ("be", "UInt32", "ld_u32({b} + 12)"), ("qw", "UInt32", "ld_u32({b} + 16 + l4)")]
def xl(ind, pre, base, decl):
    for e in range(8):
        t = "<Float32>" if decl else ""
        w(f"{ind}{pre}{e}{t} = ld_v4_f32({base} + {128 if e >= 4 else 0}, {e % 4})")
I = "            "
for k in range(D):
    w(f"        sbp{k}<Int> = {k}")
    w(f"        if (sbp{k} >= nsb) {{ sbp{k} = nsb - 1 }}")
    xl("        ", f"xn{k}_", f"xr + sbp{k} * 1024", True)
    for r in range(R):
        for (nm, ty, ex) in RAW:
            w(f"        {nm}n{k}_{r}<{ty}> = {ex.format(b='rb'+str(r)+' + sbp'+str(k)+' * 144')}")
w("        sb<Int> = 0")
w("        while (sb < nsb) {")
for e in range(8):
    w(f"{I}xv{e}<Float32> = xn0_{e}")
for r in range(R):
    for (nm, ty, ex) in RAW:
        w(f"{I}{nm}{r}<{ty}> = {nm}n0_{r}")
for k in range(1, D):
    for e in range(8):
        w(f"{I}xn{k-1}_{e} = xn{k}_{e}")
    for r in range(R):
        for (nm, ty, ex) in RAW:
            w(f"{I}{nm}n{k-1}_{r} = {nm}n{k}_{r}")
w(f"{I}sbn<Int> = sb + {D}")
w(f"{I}if (sbn >= nsb) {{ sbn = nsb - 1 }}")
xl(I, f"xn{D-1}_", "xr + sbn * 1024", False)
for r in range(R):
    w(f"{I}bn{r}<Int> = rb{r} + sbn * 144")
    for (nm, ty, ex) in RAW:
        w(f"{I}{nm}n{D-1}_{r} = {ex.format(b='bn'+str(r))}")
for r in range(R):
    w(f"""{I}b0{r}<UInt32> = ba{r} >> sh
{I}b1{r}<UInt32> = bc{r} >> sh
{I}b2{r}<UInt32> = be{r} >> sh
{I}sc0{r}<UInt32> = ((b0{r} & 63) & nmk) | (((b2{r} & 15) | (((b0{r} >> 6) & 3) << 4)) & mk)
{I}m0{r}<UInt32> = ((b1{r} & 63) & nmk) | ((((b2{r} >> 4) & 15) | (((b1{r} >> 6) & 3) << 4)) & mk)
{I}sc1{r}<UInt32> = (((b0{r} >> 8) & 63) & nmk) | ((((b2{r} >> 8) & 15) | (((b0{r} >> 14) & 3) << 4)) & mk)
{I}m1{r}<UInt32> = (((b1{r} >> 8) & 63) & nmk) | ((((b2{r} >> 12) & 15) | (((b1{r} >> 14) & 3) << 4)) & mk)
{I}ds0{r}<Float32> = df{r} * (sc0{r} as Float32)
{I}dm0{r}<Float32> = mnf{r} * (m0{r} as Float32)
{I}ds1{r}<Float32> = df{r} * (sc1{r} as Float32)
{I}dm1{r}<Float32> = mnf{r} * (m1{r} as Float32)""")
    for (nm, s) in (("A", 0), ("B", 8), ("C", 4), ("D", 12)):
        w(f"{I}v{nm}{r}<Float32> = (((qw{r} >> {s}) & 983055) as Float32)")
        w(f"{I}h{nm}{r}<Float32> = (v{nm}{r} * c16 + cmg) - cmg")
        w(f"{I}l{nm}{r}<Float32> = v{nm}{r} - h{nm}{r} * c65")
    terms = [("0", "lA", "0"), ("1", "lB", "0"), ("2", "hA", "0"), ("3", "hB", "0"),
             ("4", "lC", "1"), ("5", "lD", "1"), ("6", "hC", "1"), ("7", "hD", "1")]
    for (e, q, g) in terms:
        w(f"{I}acc{r} = acc{r} + xv{e} * (ds{g}{r} * {q}{r} - dm{g}{r})")
w("            sb = sb + 1")
w("        }")
for r in range(R):
    w(f"""        s{r}<Float> = acc{r} as Float
        s{r} = s{r} + shfl_down_f64(s{r}, 16)
        s{r} = s{r} + shfl_down_f64(s{r}, 8)
        s{r} = s{r} + shfl_down_f64(s{r}, 4)
        s{r} = s{r} + shfl_down_f64(s{r}, 2)
        s{r} = s{r} + shfl_down_f64(s{r}, 1)
        if (l == 0) {{
            if (n0 + {r} < N) {{
                if (YE == 4) {{ st_f32(Y + (n0 + {r}) * 4, s{r} as Float32) }} else {{
                    if (RS != 0) {{ s{r} = ld_f64(RS + (n0 + {r}) * 8) + s{r} }}
                    st_f64(Y + (n0 + {r}) * 8, s{r})
                }}
            }}
        }}""")
w("    }")
w("}")
open(OUTF, "w").write("\n".join(out) + "\n")

#!/usr/bin/env python3
# Structure after llama.cpp ggml-cuda/gated_delta_net.cu (MIT), see THIRD-PARTY.md.
"""gen_rdeltag.py: emit native/kernels/rdeltag.vyb, delta_step_g32, the f32 GDN decode state step with the
state held in registers (VYB_DSG, needs VYB_GDN32=1 and S == 128). Grid Hv*S/32 blocks of 256 threads: the block
owns 32 state columns j (one per lane), warp w owns rows i = w + 8r (r < 16). Each thread loads its 16 state
values once, forms partial S^T k and S^T q sums in f32, the 8 warp partials are summed in f64 via shared, then
the updated state is written straight from registers: one DRAM read and one write of the f32 state, no serial
recurrence. Structure follows llama.cpp's gated_delta_net CUDA kernel (MIT, see THIRD-PARTY.md). Not
bit-identical to the f64 path (KLD-checked); VYB_EXACT keeps delta_step_x."""
import sys
R = 16
o = []
w = o.append
w("// generated by native/tools/gen_rdeltag.py; see that file for the layout.")
w("// Structure after llama.cpp ggml-cuda/gated_delta_net.cu (MIT), see THIRD-PARTY.md.")
w("import vmath::{vexp}")
w("")
w("delta_step_g32(p<Int>) -> {")
for n, off in [("Q",0),("Kp",8),("V",16),("G",24),("BE",32),("SIN",40),("SOUT",48),("OUT",56),("S",72),("Hk",80)]:
    w(f"    {n}<Int> = ld_i64(p + {off})")
w("    sc<Float> = ld_f64(p + 96)")
w("    nb<Int> = S / 32")
w("    h<Int> = blk_x() / nb")
w("    lane<Int> = tid_x() % 32")
w("    j<Int> = (blk_x() % nb) * 32 + lane")
w("    wq<Int> = tid_x() / 32")
w("    hk<Int> = h % Hk")
w("    kb<Int> = Kp + S * hk * 8")
w("    qb<Int> = Q + S * hk * 8")
w("    rw<Int> = SIN + (S * S * h + j) * 4")
w("    st<Int> = S * 4")
for r in range(R):
    w(f"    s{r}<Float32> = ld_f32(rw + (wq + {8*r}) * st)")
for r in range(R):
    w(f"    k{r}<Float32> = (ld_f64(kb + (wq + {8*r}) * 8) as Float32)")
    w(f"    q{r}<Float32> = (ld_f64(qb + (wq + {8*r}) * 8) as Float32)")
w("    pk<Float32> = s0 * k0")
w("    pq<Float32> = s0 * q0")
w("    pkq<Float32> = k0 * q0")
for r in range(1, R):
    w(f"    pk = pk + s{r} * k{r}")
    w(f"    pq = pq + s{r} * q{r}")
    w(f"    pkq = pkq + k{r} * q{r}")
w("    st_shared_f64(wq * 32 + lane, (pk as Float))")
w("    st_shared_f64(256 + wq * 32 + lane, (pq as Float))")
w("    if (lane == 0) { st_shared_f64(512 + wq, (pkq as Float)) }")
w("    kernel_barrier()")
w("    acc<Float> = 0.0")
w("    acq<Float> = 0.0")
w("    kq<Float> = 0.0")
for i in range(8):
    w(f"    acc = acc + ld_shared_f64({i * 32} + lane)")
    w(f"    acq = acq + ld_shared_f64({256 + i * 32} + lane)")
    w(f"    kq = kq + ld_shared_f64({512 + i})")
w("    gexp<Float> = vexp(ld_f64(G + h * 8))")
w("    be<Float> = ld_f64(BE + h * 8)")
w("    del<Float> = (ld_f64(V + (j + S * h) * 8) - gexp * acc) * be")
w("    if (wq == 0) { st_f64(OUT + (j + S * h) * 8, sc * (gexp * acq + del * kq)) }")
w("    ge<Float32> = (gexp as Float32)")
w("    dl<Float32> = (del as Float32)")
w("    ww<Int> = SOUT + (S * S * h + j) * 4")
for r in range(R):
    w(f"    st_f32(ww + (wq + {8*r}) * st, ge * s{r} + dl * k{r})")
w("}")
open(sys.argv[1] if len(sys.argv) > 1 else "native/kernels/rdeltag.vyb", "w").write("\n".join(o) + "\n")

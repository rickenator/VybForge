# Generates rgemv7.vyb: q8_1 / dp4a variant of the rgemv6 llama.cpp-style IQ2_S / IQ3_S decode GEMVs
# (opt-in VYB_RGMAP=1 VYB_RGQ8=1). xq8 quantises x per 32-value block to int8 (scale amax/127, round to
# nearest even, layout: K int8 bytes then K/32 f32 scales); gemv_iq{2,3}s_q apply the IQ sign masks with
# vsub4 and dot the signed grid bytes with dp4a_s32, scaling the int sums per ib32 (as llama.cpp
# vec_dot_iq2_s_q8_1 / vec_dot_iq3_s_q8_1, MIT). NOT bit-identical; validated by greedy match + KLD.
# Lane map as rgemv6 (one ib32 per lane, 8 lanes per super-block, 1 row per warp); grid in shared.
# usage: gen_rgemv7.py out.vyb [TPB]; compile with --kernel-shared 8192.
import sys
OUTF = sys.argv[1] if len(sys.argv) > 1 else "rgemv7.vyb"
TPB = int(sys.argv[2]) if len(sys.argv) > 2 else 512
RB = TPB // 32
out = []
w = out.append
w(f"// GENERATED by gen_rgemv7.py (TPB={TPB}). Ridge IQ decode GEMVs on q8_1 activations with dp4a.\n")

def kern(name, bs, gb, iq3):
    w(f"""{name}(p<Int>) -> {{
    W<Int> = ld_i64(p + 0)
    X<Int> = ld_i64(p + 8)
    Y<Int> = ld_i64(p + 16)
    N<Int> = ld_i64(p + 32)
    K<Int> = ld_i64(p + 40)
    YE<Int> = ld_i64(p + 48)
    RS<Int> = ld_i64(p + 120)
    G<Int> = ld_i64(p + 128)
    tid<Int> = tid_x()
    l<Int> = tid % 32
    n0<Int> = blk_x() * {RB} + tid / 32
    nsb<Int> = K / 256
    c1<Float32> = 1.0 as Float32
    c2<Float32> = 2.0 as Float32
    ch<Float32> = 0.5 as Float32
    cq<Float32> = 0.25 as Float32
    acc<Float32> = 0.0
    ff<UInt32> = 255 as UInt32""")
    for c in range(0, gb // 16, TPB):
        w(f"""    if (tid + {c} < {gb // 16}) {{
        st_shared_v4_u32((tid + {c}) * 16, ld_v4_u32(G + (tid + {c}) * 16, 0), ld_v4_u32(G + (tid + {c}) * 16, 1), ld_v4_u32(G + (tid + {c}) * 16, 2), ld_v4_u32(G + (tid + {c}) * 16, 3))
    }}""")
    w("""    kernel_barrier()
    ib<Int> = l % 8
    if (n0 < N) {
        rb<Int> = W + n0 * (nsb * BS)
        sb<Int> = l / 8
        while (sb < nsb) {
            bb<Int> = rb + sb * BS
            xq<Int> = X + sb * 256 + ib * 32
            dx<Float32> = ld_f32n(X + K + (sb * 8 + ib) * 4)""".replace("BS", str(bs)))
    I = "            "
    for c in range(8):
        w(f"{I}qx{c}<UInt32> = ld_v4_u32(xq + {16 * (c // 4)}, {c % 4})")
    w(f"{I}d<Float32> = ld_f16(bb)")
    if iq3:
        for k in range(4):
            w(f"{I}qw{k}<Int> = (ld_u16(bb + 2 + 8 * ib + {2*k}) as Int) & 65535")
        w(f"{I}qh<Int> = (ld_i8(bb + 66 + ib) as Int) & 255")
        w(f"{I}s01<Int> = (ld_u16(bb + 74 + 4 * ib) as Int) & 65535")
        w(f"{I}s23<Int> = (ld_u16(bb + 76 + 4 * ib) as Int) & 65535")
        w(f"{I}sc<Int> = (ld_i8(bb + 106 + ib / 2) as Int) & 255")
    else:
        w(f"{I}q01<Int> = (ld_u16(bb + 2 + 4 * ib) as Int) & 65535")
        w(f"{I}q23<Int> = (ld_u16(bb + 4 + 4 * ib) as Int) & 65535")
        w(f"{I}s01<Int> = (ld_u16(bb + 34 + 4 * ib) as Int) & 65535")
        w(f"{I}s23<Int> = (ld_u16(bb + 36 + 4 * ib) as Int) & 65535")
        w(f"{I}qh<Int> = (ld_i8(bb + 66 + ib) as Int) & 255")
        w(f"{I}sc<Int> = (ld_i8(bb + 74 + ib) as Int) & 255")
    for k in range(4):
        sv = "s01" if k < 2 else "s23"
        sh = "" if k % 2 == 0 else " >> 8"
        if iq3:
            w(f"{I}i1_{k}<Int> = (qw{k} & 255) | ((qh << {8 - 2*k}) & 256)")
            w(f"{I}i2_{k}<Int> = (qw{k} >> 8) | ((qh << {7 - 2*k}) & 256)")
            w(f"{I}ga{k}<UInt32> = ld_shared_u32(i1_{k} * 4)")
            w(f"{I}gb{k}<UInt32> = ld_shared_u32(i2_{k} * 4)")
        else:
            qv = "q01" if k < 2 else "q23"
            w(f"{I}ix{k}<Int> = (({qv}{sh}) & 255) | ((qh << {8 - 2*k}) & 768)")
            w(f"{I}ga{k}<UInt32> = ld_shared_v2_u32(ix{k} * 8, 0)")
            w(f"{I}gb{k}<UInt32> = ld_shared_v2_u32(ix{k} * 8, 1)")
        w(f"{I}sg{k}<UInt32> = (({sv}{sh}) & 255) as UInt32")
        # Sign handling (2026-10-26): the grid bytes are non-negative (< 128), so
        #   sum s_i g_i x_i = dp4a(g, x) - 2 * dp4a(g, x & m),  m = 0xFF per byte where the sign bit is set.
        # m from a nibble without per-bit extraction: n * 0x204081 spreads bits 0..3 to bits 0/8/16/24 (the
        # shifted copies occupy disjoint bit ranges, so no carries), & 0x01010101, * 255. Integer-identical
        # to the old vsub4(g ^ m, m) form (vsub4 is a 7-op SIMD emulation in PTX on sm_86).
        for h in range(2):
            nib = f"(sg{k} >> {4*h}) & (15 as UInt32)" if h else f"sg{k} & (15 as UInt32)"
            w(f"{I}m{k}_{h}<UInt32> = ((({nib}) * (2113665 as UInt32)) & (16843009 as UInt32)) * ff")
        w(f"{I}si{k}<CInt> = dp4a_s32(gb{k}, qx{2*k+1}, dp4a_s32(ga{k}, qx{2*k}, 0)) - 2 * dp4a_s32(gb{k}, qx{2*k+1} & m{k}_1, dp4a_s32(ga{k}, qx{2*k} & m{k}_0, 0))")
    if iq3:
        w(f"{I}db<Float32> = d * (c1 + c2 * (((sc >> (4 * (ib % 2))) & 15) as Float32))")
        w(f"{I}acc = acc + dx * db * ((si0 + si1 + si2 + si3) as Float32)")
    else:
        w(f"{I}dlo<Float32> = d * (((sc & 15) as Float32) + ch) * cq")
        w(f"{I}dhi<Float32> = d * ((((sc >> 4) & 15) as Float32) + ch) * cq")
        w(f"{I}acc = acc + dx * (dlo * ((si0 + si1) as Float32) + dhi * ((si2 + si3) as Float32))")
    w(f"""{I}sb = sb + 4
        }}
        s<Float> = acc as Float
        s = s + shfl_down_f64(s, 16)
        s = s + shfl_down_f64(s, 8)
        s = s + shfl_down_f64(s, 4)
        s = s + shfl_down_f64(s, 2)
        s = s + shfl_down_f64(s, 1)
        if (l == 0) {{
            if (YE == 4) {{ st_f32(Y + n0 * 4, s as Float32) }} else {{
                if (RS != 0) {{ s = ld_f64(RS + n0 * 8) + s }}
                st_f64(Y + n0 * 8, s)
            }}
        }}
    }}
}}
""")

kern("gemv_iq2s_q", 82, 8192, False)
kern("gemv_iq3s_q", 110, 2048, True)
w("""
// q8_1-style activation quantiser for gemv_*_q: per 32-value block d = amax/127, q = rni(x/d) clamped to
// +-127. Y: K int8 bytes, then K/32 f32 scales at Y + K. +0 X (f32) +8 Y +16 K. Grid ceil(K/256) x 256.
xq8(p<Int>) -> {
    X<Int> = ld_i64(p + 0)
    Y<Int> = ld_i64(p + 8)
    K<Int> = ld_i64(p + 16)
    i<Int> = blk_x() * 256 + tid_x()
    x<Float32> = 0.0 as Float32
    if (i < K) { x = ld_f32n(X + i * 4) }
    a<Float32> = max_f32(x, (0.0 as Float32) - x)
    a = max_f32(a, shfl_xor_f32(a, 16))
    a = max_f32(a, shfl_xor_f32(a, 8))
    a = max_f32(a, shfl_xor_f32(a, 4))
    a = max_f32(a, shfl_xor_f32(a, 2))
    a = max_f32(a, shfl_xor_f32(a, 1))
    dd<Float32> = a / (127.0 as Float32)
    iv<Float32> = 0.0 as Float32
    if (a > (0.0 as Float32)) { iv = (127.0 as Float32) / a }
    if (i < K) {
        st_i8(Y + i, sat_s8(rni_f32(x * iv)))
        if (i % 32 == 0) { st_f32(Y + K + (i / 32) * 4, dd) }
    }
}
""")
open(OUTF, "w").write("\n".join(out))

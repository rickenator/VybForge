# Generates rgemv7.vyb: q8_1 / dp4a variant of the rgemv6 llama.cpp-style IQ2_S / IQ3_S decode GEMVs
# (opt-in VYB_RGMAP=1 VYB_RGQ8=1). xq8 quantises x per 32-value block to int8 (scale amax/127, round to
# nearest even, layout: K int8 bytes then K/32 f32 scales); gemv_iq{2,3}s_q apply the IQ sign masks with
# vsub4 and dot the signed grid bytes with dp4a_s32, scaling the int sums per ib32 (as llama.cpp
# vec_dot_iq2_s_q8_1 / vec_dot_iq3_s_q8_1, MIT). NOT bit-identical; validated by greedy match + KLD.
# Lane map as rgemv6 (one ib32 per lane, 8 lanes per super-block, 1 row per warp); grid in shared.
# usage: gen_rgemv7.py out.vyb [TPB] [UNR=1; 2 = 2-way load-ahead unroll, exact but measured slower: 32.15 vs 32.51 tg128]; compile with --kernel-shared 8192.
import sys
OUTF = sys.argv[1] if len(sys.argv) > 1 else "rgemv7.vyb"
TPB = int(sys.argv[2]) if len(sys.argv) > 2 else 512
RB = TPB // 32
UNR = int(sys.argv[3]) if len(sys.argv) > 3 else 1
out = []
w = out.append
w(f"// GENERATED by gen_rgemv7.py (TPB={TPB}). Ridge IQ decode GEMVs on q8_1 activations with dp4a.\n")

def kern(name, bs, gb, iq3):
    w(f"""{name}(p<Int>) -> {{
    W<Int> = ld_i64(p + 0)
    X<Int> = ld_i64(p + 8)
    Y<Int> = ld_i64(p + 16)
    N<Int> = ld_i64(p + 32)
    K<Int> = ld_i64(p + 40)
    YE<Int> = ld_i64(p + 48)
    RS<Int> = ld_i64(p + 120)
    G<Int> = ld_i64(p + 128)
    tid<Int> = tid_x()
    l<Int> = tid % 32
    n0<Int> = blk_x() * {RB} + tid / 32
    nsb<Int> = K / 256
    c1<Float32> = 1.0 as Float32
    c2<Float32> = 2.0 as Float32
    ch<Float32> = 0.5 as Float32
    cq<Float32> = 0.25 as Float32
    acc<Float32> = 0.0
    ff<UInt32> = 255 as UInt32""")
    for c in range(0, gb // 16, TPB):
        w(f"""    if (tid + {c} < {gb // 16}) {{
        st_shared_v4_u32((tid + {c}) * 16, ldg_v4_u32(G + (tid + {c}) * 16, 0), ldg_v4_u32(G + (tid + {c}) * 16, 1), ldg_v4_u32(G + (tid + {c}) * 16, 2), ldg_v4_u32(G + (tid + {c}) * 16, 3))
    }}""")
    w("""    kernel_barrier()
    ib<Int> = l % 8
    if (n0 < N) {
        rb<Int> = W + n0 * (nsb * BS)
        sb<Int> = l / 8""".replace("BS", str(bs)))
    def body(S, sbe):
        L = []; C = []
        L.append(f"bb{S}<Int> = rb + ({sbe}) * {bs}")
        L.append(f"xq{S}<Int> = X + ({sbe}) * 256 + ib * 32")
        L.append(f"dx{S}<Float32> = ld_f32n(X + K + (({sbe}) * 8 + ib) * 4)")
        for c in range(8):
            L.append(f"qx{c}{S}<UInt32> = ldg_v4_u32(xq{S} + {16 * (c // 4)}, {c % 4})")
        L.append(f"d{S}<Float32> = ld_f16(bb{S})")
        if iq3:
            for k in range(4):
                L.append(f"qw{k}{S}<Int> = (ld_u16(bb{S} + 2 + 8 * ib + {2*k}) as Int) & 65535")
            L.append(f"qh{S}<Int> = (ld_i8(bb{S} + 66 + ib) as Int) & 255")
            L.append(f"s01{S}<Int> = (ld_u16(bb{S} + 74 + 4 * ib) as Int) & 65535")
            L.append(f"s23{S}<Int> = (ld_u16(bb{S} + 76 + 4 * ib) as Int) & 65535")
            L.append(f"sc{S}<Int> = (ld_i8(bb{S} + 106 + ib / 2) as Int) & 255")
        else:
            L.append(f"q01{S}<Int> = (ld_u16(bb{S} + 2 + 4 * ib) as Int) & 65535")
            L.append(f"q23{S}<Int> = (ld_u16(bb{S} + 4 + 4 * ib) as Int) & 65535")
            L.append(f"s01{S}<Int> = (ld_u16(bb{S} + 34 + 4 * ib) as Int) & 65535")
            L.append(f"s23{S}<Int> = (ld_u16(bb{S} + 36 + 4 * ib) as Int) & 65535")
            L.append(f"qh{S}<Int> = (ld_i8(bb{S} + 66 + ib) as Int) & 255")
            L.append(f"sc{S}<Int> = (ld_i8(bb{S} + 74 + ib) as Int) & 255")
        for k in range(4):
            sv = ("s01" if k < 2 else "s23") + S
            sh = "" if k % 2 == 0 else " >> 8"
            if iq3:
                C.append(f"i1_{k}{S}<Int> = (qw{k}{S} & 255) | ((qh{S} << {8 - 2*k}) & 256)")
                C.append(f"i2_{k}{S}<Int> = (qw{k}{S} >> 8) | ((qh{S} << {7 - 2*k}) & 256)")
                C.append(f"ga{k}{S}<UInt32> = ld_shared_u32(i1_{k}{S} * 4)")
                C.append(f"gb{k}{S}<UInt32> = ld_shared_u32(i2_{k}{S} * 4)")
            else:
                qv = ("q01" if k < 2 else "q23") + S
                C.append(f"ix{k}{S}<Int> = (({qv}{sh}) & 255) | ((qh{S} << {8 - 2*k}) & 768)")
                C.append(f"ga{k}{S}<UInt32> = ld_shared_v2_u32(ix{k}{S} * 8, 0)")
                C.append(f"gb{k}{S}<UInt32> = ld_shared_v2_u32(ix{k}{S} * 8, 1)")
            C.append(f"sg{k}{S}<UInt32> = (({sv}{sh}) & 255) as UInt32")
            # Sign handling: grid bytes are < 128, so sum s_i g_i x_i = dp4a(g, x) - 2 * dp4a(g, x & m) with
            # m = bytemask4(sign nibble) (Vyb intrinsics, vyb-wt 2026-10-26); integer-identical to vsub4(g ^ m, m).
            C.append(f"m{k}_0{S}<UInt32> = bytemask4(sg{k}{S})")
            C.append(f"m{k}_1{S}<UInt32> = bytemask4(sg{k}{S} >> 4)")
            C.append(f"si{k}{S}<CInt> = dp4a_sgn_s32(gb{k}{S}, qx{2*k+1}{S}, m{k}_1{S}, dp4a_sgn_s32(ga{k}{S}, qx{2*k}{S}, m{k}_0{S}, 0))")
        if iq3:
            C.append(f"db{S}<Float32> = d{S} * (c1 + c2 * (((sc{S} >> (4 * (ib % 2))) & 15) as Float32))")
            C.append(f"acc = acc + dx{S} * db{S} * ((si0{S} + si1{S} + si2{S} + si3{S}) as Float32)")
        else:
            C.append(f"dlo{S}<Float32> = d{S} * (((sc{S} & 15) as Float32) + ch) * cq")
            C.append(f"dhi{S}<Float32> = d{S} * ((((sc{S} >> 4) & 15) as Float32) + ch) * cq")
            C.append(f"acc = acc + dx{S} * (dlo{S} * ((si0{S} + si1{S}) as Float32) + dhi{S} * ((si2{S} + si3{S}) as Float32))")
        return L, C
    I = "            "
    if UNR == 2:
        # 2-way unroll (2026-10-26): both super-blocks' loads are issued before either is used (more bytes in
        # flight per warp); the acc updates stay in the original sb order, so results are bit-identical.
        w("        while (sb + 4 < nsb) {")
        La, Ca = body("_a", "sb"); Lb, Cb = body("_b", "sb + 4")
        for x in La + Lb + Ca + Cb: w(I + x)
        w(I + "sb = sb + 8")
        w("        }")
        w("        if (sb < nsb) {")
        Lt, Ct = body("_t", "sb")
        for x in Lt + Ct: w(I + x)
        w("        }")
    else:
        w("        while (sb < nsb) {")
        L0, C0 = body("", "sb")
        for x in L0 + C0: w(I + x)
        w(I + "sb = sb + 4")
        w("        }")
    w(f"""        s<Float> = acc as Float
        s = s + shfl_down_f64(s, 16)
        s = s + shfl_down_f64(s, 8)
        s = s + shfl_down_f64(s, 4)
        s = s + shfl_down_f64(s, 2)
        s = s + shfl_down_f64(s, 1)
        if (l == 0) {{
            if (YE == 4) {{ st_f32(Y + n0 * 4, s as Float32) }} else {{
                if (RS != 0) {{ s = ld_f64(RS + n0 * 8) + s }}
                st_f64(Y + n0 * 8, s)
            }}
        }}
    }}
}}
""")

kern("gemv_iq2s_q", 82, 8192, False)
kern("gemv_iq3s_q", 110, 2048, True)
w("""
// q8_1-style activation quantiser for gemv_*_q: per 32-value block d = amax/127, q = rni(x/d) clamped to
// +-127. Y: K int8 bytes, then K/32 f32 scales at Y + K. +0 X (f32) +8 Y +16 K. Grid ceil(K/256) x 256.
xq8(p<Int>) -> {
    X<Int> = ld_i64(p + 0)
    Y<Int> = ld_i64(p + 8)
    K<Int> = ld_i64(p + 16)
    i<Int> = blk_x() * 256 + tid_x()
    x<Float32> = 0.0 as Float32
    if (i < K) { x = ld_f32n(X + i * 4) }
    a<Float32> = max_f32(x, (0.0 as Float32) - x)
    a = warp_max_f32(a)
    dd<Float32> = a / (127.0 as Float32)
    iv<Float32> = 0.0 as Float32
    if (a > (0.0 as Float32)) { iv = (127.0 as Float32) / a }
    if (i < K) {
        st_i8(Y + i, sat_s8(rni_f32(x * iv)))
        if (i % 32 == 0) { st_f32(Y + K + (i / 32) * 4, dd) }
    }
}
""")
open(OUTF, "w").write("\n".join(out))

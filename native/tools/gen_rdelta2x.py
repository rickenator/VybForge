#!/usr/bin/env python3
"""Generate native/kernels/rdelta2x.vyb: delta_step_x, a bit-identical (f64) GDN decode state update
with one DRAM read + one DRAM write of the state (delta_step_u reads it twice) and NW warps of
memory-level parallelism per block.

Column-major state as in rdelta2 (element (j, i) of head h at S*S*h + i*S + j). Grid Hv*S/32 blocks
x 32*NW threads; a block owns 32 j columns of one head.
  1. all NW warps load the block's S x 32 state tile into shared (warp w takes rows i = w, w+NW, ...,
     UL loads in flight per thread), plus k and q of the head;
  2. from the shared tile, warp 0 runs the acc chain (-> del, gexp), warp 1 the acq chain, and one
     thread the kq dot (delta_step_u recomputed kq in every thread): the same expressions in the same
     i order as delta_step_u, split over warps; warp 1 then writes out;
  3. all NW warps write gexp * s + del * k[i] for the tile.
Per-element arithmetic and order are exactly delta_step_t / delta_step_u's, so the f64 result is
bit-identical. Shared: 32*S + 34 f64 slots = 33040 B at S=128 (built at 33040 so three blocks fit an SM: 192 blocks
in one wave on an 82-SM 3090). k and q are read from global (lane-uniform, L1 broadcast).
usage: gen_rdelta2x.py OUT [NW=8] [UL=8]
"""
import sys
OUT = sys.argv[1]
NW = int(sys.argv[2]) if len(sys.argv) > 2 else 8
UL = int(sys.argv[3]) if len(sys.argv) > 3 else 8
T = 0            # tile base slot
D = 32 * 128     # del slots (32), then gexp (1), kq (1)
L = []
w = L.append
w(f"// generated by native/tools/gen_rdelta2x.py (NW={NW}, UL={UL}); see that file for the layout.")
w("import vmath::{vexp}")
w(f"""
delta_step_x(p<Int>) -> {{
    Q<Int> = ld_i64(p + 0)
    Kp<Int> = ld_i64(p + 8)
    V<Int> = ld_i64(p + 16)
    G<Int> = ld_i64(p + 24)
    BE<Int> = ld_i64(p + 32)
    SIN<Int> = ld_i64(p + 40)
    SOUT<Int> = ld_i64(p + 48)
    OUT<Int> = ld_i64(p + 56)
    S<Int> = ld_i64(p + 72)
    Hk<Int> = ld_i64(p + 80)
    sc<Float> = ld_f64(p + 96)
    nb<Int> = S / 32
    h<Int> = blk_x() / nb
    lane<Int> = tid_x() % 32
    j<Int> = (blk_x() % nb) * 32 + lane
    wq<Int> = tid_x() / 32
    hk<Int> = h % Hk
    kb<Int> = Kp + S * hk * 8
    qb<Int> = Q + S * hk * 8
    rw<Int> = SIN + (S * S * h + j) * 8
    st<Int> = S * 8
    il<Int> = wq
    while (il < S) {{""")
for u in range(UL):
    w(f"        l{u}<Float> = ld_f64(rw + (il + {u * NW}) * st)")
for u in range(UL):
    w(f"        st_shared_f64({T} + (il + {u * NW}) * 32 + lane, l{u})")
w(f"""        il = il + {UL * NW}
    }}
    kernel_barrier()
    acq<Float> = 0.0
    if (wq == 0) {{
        acc<Float> = 0.0
        ib<Int> = 0
        while (ib < S) {{""")
for u in range(UL):
    w(f"            s{u}<Float> = ld_shared_f64({T} + (ib + {u}) * 32 + lane)")
for u in range(UL):
    w(f"            acc = acc + s{u} * ld_f64(kb + (ib + {u}) * 8)")
w(f"""            ib = ib + {UL}
        }}
        gexp<Float> = vexp(ld_f64(G + h * 8))
        be<Float> = ld_f64(BE + h * 8)
        del<Float> = (ld_f64(V + (j + S * h) * 8) - gexp * acc) * be
        st_shared_f64({D} + lane, del)
        if (lane == 0) {{ st_shared_f64({D + 32}, gexp) }}
    }}
    if (wq == 1) {{
        iq<Int> = 0
        while (iq < S) {{""")
for u in range(UL):
    w(f"            q{u}<Float> = ld_shared_f64({T} + (iq + {u}) * 32 + lane)")
for u in range(UL):
    w(f"            acq = acq + q{u} * ld_f64(qb + (iq + {u}) * 8)")
w(f"""            iq = iq + {UL}
        }}
    }}
    if (tid_x() == 64) {{
        kq<Float> = 0.0
        i<Int> = 0
        for (i in 0..S - 1) {{ kq = kq + ld_f64(kb + i * 8) * ld_f64(qb + i * 8) }}
        st_shared_f64({D + 33}, kq)
    }}
    kernel_barrier()
    if (wq == 1) {{
        st_f64(OUT + (j + S * h) * 8, sc * (ld_shared_f64({D + 32}) * acq + ld_shared_f64({D} + lane) * ld_shared_f64({D + 33})))
    }}
    kernel_barrier()
    dl<Float> = ld_shared_f64({D} + lane)
    ge<Float> = ld_shared_f64({D + 32})
    ww<Int> = SOUT + (S * S * h + j) * 8
    iw<Int> = wq
    while (iw < S) {{""")
for u in range(UL):
    w(f"        r{u}<Float> = ld_shared_f64({T} + (iw + {u * NW}) * 32 + lane)")
for u in range(UL):
    w(f"        st_f64(ww + (iw + {u * NW}) * st, ge * r{u} + dl * ld_f64(kb + (iw + {u * NW}) * 8))")
w(f"""        iw = iw + {UL * NW}
    }}
}}""")
open(OUT, "w").write("\n".join(L) + "\n")

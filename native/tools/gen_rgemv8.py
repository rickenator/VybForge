# Generates rgemv8.vyb: IQ2_S decode GEMV (gemv_iq2s_r) with the weight stream restructured, plus rgemv5's
# gemv_iq3s_r unchanged. Same lane map / per-lane arithmetic / reduction as gen_rgemv5.py (R=1, SM=1)
# -> bit-identical. Each warp streams its row CH super-blocks (CH*82 B) at a time as coalesced u32 loads
# (word i of the chunk held by lane i%32 in register i/32), register-prefetched PD chunks ahead; the
# per-lane bytes (scale, qs, qh, signs) and the f16 d come out of those registers by shfl_idx_u32 - no
# shared staging, no barriers, no scattered byte loads. Only the registers a field can touch (known at
# generation time, j unrolled) are shuffled. Needs nsb % CH == 0 and (CH*82) % 4 == 0.
# usage: gen_rgemv8.py out.vyb CH PD [C3]   (C3 = IQ3_S super-blocks per chunk; IQ3_S now generated the same way)
import sys
OUTF = sys.argv[1] if len(sys.argv) > 1 else "rgemv8.vyb"
CH = int(sys.argv[2]) if len(sys.argv) > 2 else 4
PD = int(sys.argv[3]) if len(sys.argv) > 3 else 1
assert (CH * 82) % 4 == 0
NW = CH * 82 // 4          # words per chunk
NR = (NW + 31) // 32       # registers per lane per chunk
out = []
w = out.append
w(f"""// GENERATED by gen_rgemv8.py (CH={CH} super-blocks per chunk, PD={PD} chunks prefetched). Ridge IQ2_S decode
// GEMV via coalesced u32 row loads + shfl_idx byte extraction; bit-identical to rgemv5 (gen_rgemv5.py 1 .. 1 1 0 2).
// Launch ceil(N/16) blocks x 512. Needs K/256 % {CH} == 0. Compile with --kernel-shared 8192. Derived from llama.cpp (MIT).

gemv_iq2s_r(p<Int>) -> {{
    W<Int> = ld_i64(p + 0)
    X<Int> = ld_i64(p + 8)
    Y<Int> = ld_i64(p + 16)
    N<Int> = ld_i64(p + 32)
    K<Int> = ld_i64(p + 40)
    YE<Int> = ld_i64(p + 48)
    RS<Int> = ld_i64(p + 120)
    G<Int> = ld_i64(p + 128)
    tid<Int> = tid_x()
    l<Int> = tid % 32
    n0<Int> = blk_x() * 16 + tid / 32
    nsb<Int> = K / 256
    c1<Float32> = 1.0 as Float32
    c2<Float32> = 2.0 as Float32
    ch<Float32> = 0.5 as Float32
    cq<Float32> = 0.25 as Float32
    acc0<Float32> = 0.0
    if (tid < 512) {{
        st_shared_v4_u32(tid * 16, ld_v4_u32(G + tid * 16, 0), ld_v4_u32(G + tid * 16, 1), ld_v4_u32(G + tid * 16, 2), ld_v4_u32(G + tid * 16, 3))
    }}
    kernel_barrier()
    if (n0 < N) {{
        ib<Int> = l / 4
        l2<Int> = l % 4
        shs<Int> = (l2 / 2) * 4
        shq<Int> = 8 - 2 * l2
        xr<Int> = X + l * 32
        rbs<Int> = nsb * 82
        rb0<Int> = W + n0 * rbs
        nch<Int> = nsb / {CH}""")
def ldchunk(pref, cexpr, decl):
    for r in range(NR):
        t = "<UInt32>" if decl else ""
        last = (r == NR - 1) and (NW % 32 != 0)
        if decl:
            w(f"        {pref}{r}{t} = 0 as UInt32")
        if last:
            w(f"        if (l < {NW % 32}) {{ {pref}{r} = ld_u32(rb0 + ({cexpr}) * {CH * 82} + {r * 128} + l * 4) }}")
        else:
            w(f"        {pref}{r} = ld_u32(rb0 + ({cexpr}) * {CH * 82} + {r * 128} + l * 4)")
# prefetch registers: q{d}_{r} holds chunk c+d
for d in range(PD + 1):
    w(f"        cp{d}<Int> = {d}")
    w(f"        if (cp{d} >= nch) {{ cp{d} = nch - 1 }}")
    ldchunk(f"q{d}_", f"cp{d}", True)
w("""        c<Int> = 0
        while (c < nch) {""")
for r in range(NR):
    w(f"            u{r}<UInt32> = q0_{r}")
for d in range(PD):
    for r in range(NR):
        w(f"            q{d}_{r} = q{d + 1}_{r}")
w(f"""            cn<Int> = c + {PD + 1}
            if (cn >= nch) {{ cn = nch - 1 }}""")
for r in range(NR):
    last = (r == NR - 1) and (NW % 32 != 0)
    if last:
        w(f"            if (l < {NW % 32}) {{ q{PD}_{r} = ld_u32(rb0 + cn * {CH * 82} + {r * 128} + l * 4) }}")
    else:
        w(f"            q{PD}_{r} = ld_u32(rb0 + cn * {CH * 82} + {r * 128} + l * 4)")

def fetch(name, j, base, lane_off, span, SB=82, mask=255):
    # field at chunk offset j*SB + base + lane_off(l), lane_off in [0, span); 1 byte (mask 255) or an even-aligned u16
    o_lo = j * SB + base
    o_hi = o_lo + span - 1
    regs = sorted(set(((o // 4) // 32) for o in range(o_lo, o_hi + 1)))
    w(f"            o{name}{j}<Int> = {o_lo} + {lane_off}")
    w(f"            s{name}{j}<Int> = (o{name}{j} / 4) % 32")
    w(f"            v{name}{j}<UInt32> = shfl_idx_u32(u{regs[0]}, s{name}{j})")
    for r in regs[1:]:
        w(f"            t{name}{j}_{r}<UInt32> = shfl_idx_u32(u{r}, s{name}{j})")
        w(f"            if ((o{name}{j} / 4) / 32 == {r}) {{ v{name}{j} = t{name}{j}_{r} }}")
    w(f"            b{name}{j}<Int> = ((v{name}{j} >> (((o{name}{j} % 4) * 8) as UInt32)) as Int) & {mask}")

for j in range(CH):
    od = j * 82
    wd = od // 4
    w(f"            sb{j}<Int> = c * {CH} + {j}")
    w(f"            dw{j}<UInt32> = shfl_idx_u32(u{wd // 32}, {wd % 32})")
    w(f"            d{j}<Float32> = {'h_lo' if od % 4 == 0 else 'h_hi'}(dw{j})")
    fetch("sc", j, 74, "ib", 8)
    fetch("qs", j, 2, "l", 32)
    fetch("qh", j, 66, "ib", 8)
    fetch("sg", j, 34, "l", 32)
    for q in range(8):
        w(f"            x{q}_{j}<Float32> = ld_v4_f32(xr + sb{j} * 1024 + {0 if q < 4 else 16}, {q % 4})")
    w(f"""            dl{j}<Float32> = d{j} * ((((bsc{j} >> shs) & 15) as Float32) + ch) * cq
            idx{j}<Int> = bqs{j} | ((bqh{j} << shq) & 768)
            g0_{j}<UInt32> = ld_shared_v2_u32(idx{j} * 8, 0)
            g1_{j}<UInt32> = ld_shared_v2_u32(idx{j} * 8, 1)
            sg_{j}<UInt32> = bsg{j} as UInt32""")
    for q in range(8):
        g = f"g{q // 4}_{j}"
        sh = (q % 4) * 8
        gs = f"({g})" if sh == 0 else f"({g} >> {sh})"
        ss = f"(sg_{j} & 1)" if q == 0 else f"((sg_{j} >> {q}) & 1)"
        w(f"            w{q}_{j}<Float32> = (({gs} & 255) as Float32) * (c1 - c2 * ({ss} as Float32))")
    w(f"            pt{j}<Float32> = x0_{j} * w0_{j}")
    for q in range(1, 8):
        w(f"            pt{j} = pt{j} + x{q}_{j} * w{q}_{j}")
    w(f"            acc0 = acc0 + dl{j} * pt{j}")
w("""            c = c + 1
        }
    }
    if (n0 < N) {
        s0<Float> = acc0 as Float
        s0 = s0 + shfl_down_f64(s0, 16)
        s0 = s0 + shfl_down_f64(s0, 8)
        s0 = s0 + shfl_down_f64(s0, 4)
        s0 = s0 + shfl_down_f64(s0, 2)
        s0 = s0 + shfl_down_f64(s0, 1)
        if (l == 0) {
            if (YE == 4) { st_f32(Y + n0 * 4, s0 as Float32) } else {
                if (RS != 0) { s0 = ld_f64(RS + n0 * 8) + s0 }
                st_f64(Y + n0 * 8, s0)
            }
        }
    }
}
""")
C3 = int(sys.argv[4]) if len(sys.argv) > 4 else 4     # IQ3_S super-blocks per chunk (110 B each)
NW = C3 * 110 // 4
NR = (NW + 31) // 32
assert (C3 * 110) % 4 == 0
w(f"""
// IQ3_S (110 B super-block: d f16 @0, qs @2, qh @66, signs @74, scales @106), same lane map as rgemv5
// (lane l: qs u16 @2+2l, qh @66+l/4, signs @74+l, scale nibble @106+l/8), C3={C3} super-blocks per chunk.
gemv_iq3s_r(p<Int>) -> {{
    W<Int> = ld_i64(p + 0)
    X<Int> = ld_i64(p + 8)
    Y<Int> = ld_i64(p + 16)
    N<Int> = ld_i64(p + 32)
    K<Int> = ld_i64(p + 40)
    YE<Int> = ld_i64(p + 48)
    RS<Int> = ld_i64(p + 120)
    G<Int> = ld_i64(p + 128)
    tid<Int> = tid_x()
    l<Int> = tid % 32
    n0<Int> = blk_x() * 16 + tid / 32
    nsb<Int> = K / 256
    c1<Float32> = 1.0 as Float32
    c2<Float32> = 2.0 as Float32
    acc0<Float32> = 0.0
    if (tid < 128) {{
        st_shared_v4_u32(tid * 16, ld_v4_u32(G + tid * 16, 0), ld_v4_u32(G + tid * 16, 1), ld_v4_u32(G + tid * 16, 2), ld_v4_u32(G + tid * 16, 3))
    }}
    kernel_barrier()
    if (n0 < N) {{
        g<Int> = l / 8
        hf<Int> = (l % 8) / 4
        l3<Int> = l % 4
        shs<Int> = hf * 4
        sh1<Int> = 8 - 2 * l3
        sh2<Int> = 7 - 2 * l3
        l2x<Int> = 2 * l
        l4<Int> = l / 4
        xr<Int> = X + l * 32
        rbs<Int> = nsb * 110
        rb0<Int> = W + n0 * rbs
        nch<Int> = nsb / {C3}""")
def ldc(pref, cexpr, decl, ind):
    for r in range(NR):
        last = (r == NR - 1) and (NW % 32 != 0)
        if decl:
            w(f"{ind}{pref}{r}<UInt32> = 0 as UInt32")
        ld = f"{pref}{r} = ld_u32(rb0 + ({cexpr}) * {C3 * 110} + {r * 128} + l * 4)"
        w(f"{ind}if (l < {NW % 32}) {{ {ld} }}" if last else f"{ind}{ld}")
for d in range(PD + 1):
    w(f"        cp{d}<Int> = {d}")
    w(f"        if (cp{d} >= nch) {{ cp{d} = nch - 1 }}")
    ldc(f"q{d}_", f"cp{d}", True, "        ")
w("""        c<Int> = 0
        while (c < nch) {""")
for r in range(NR):
    w(f"            u{r}<UInt32> = q0_{r}")
for d in range(PD):
    for r in range(NR):
        w(f"            q{d}_{r} = q{d + 1}_{r}")
w(f"""            cn<Int> = c + {PD + 1}
            if (cn >= nch) {{ cn = nch - 1 }}""")
ldc(f"q{PD}_", "cn", False, "            ")
for j in range(C3):
    od = j * 110
    wd = od // 4
    w(f"            sb{j}<Int> = c * {C3} + {j}")
    w(f"            dw{j}<UInt32> = shfl_idx_u32(u{wd // 32}, {wd % 32})")
    w(f"            d{j}<Float32> = {'h_lo' if od % 4 == 0 else 'h_hi'}(dw{j})")
    fetch("sc", j, 106, "g", 4, 110)
    fetch("qh", j, 66, "l4", 8, 110)
    fetch("qw", j, 2, "l2x", 63, 110, 65535)
    fetch("sg", j, 74, "l", 32, 110)
    for q in range(8):
        w(f"            x{q}_{j}<Float32> = ld_v4_f32(xr + sb{j} * 1024 + {0 if q < 4 else 16}, {q % 4})")
    w(f"""            db{j}<Float32> = d{j} * (c1 + c2 * (((bsc{j} >> shs) & 15) as Float32))
            i1_{j}<Int> = (bqw{j} & 255) | ((bqh{j} << sh1) & 256)
            i2_{j}<Int> = (bqw{j} >> 8) | ((bqh{j} << sh2) & 256)
            g0_{j}<UInt32> = ld_shared_u32(i1_{j} * 4)
            g1_{j}<UInt32> = ld_shared_u32(i2_{j} * 4)
            sg_{j}<UInt32> = bsg{j} as UInt32""")
    for q in range(8):
        gg = f"g{q // 4}_{j}"
        sh = (q % 4) * 8
        gs = f"({gg})" if sh == 0 else f"({gg} >> {sh})"
        ss = f"(sg_{j} & 1)" if q == 0 else f"((sg_{j} >> {q}) & 1)"
        w(f"            w{q}_{j}<Float32> = (({gs} & 255) as Float32) * (c1 - c2 * ({ss} as Float32))")
    w(f"            pt{j}<Float32> = x0_{j} * w0_{j}")
    for q in range(1, 8):
        w(f"            pt{j} = pt{j} + x{q}_{j} * w{q}_{j}")
    w(f"            acc0 = acc0 + db{j} * pt{j}")
w("""            c = c + 1
        }
    }
    if (n0 < N) {
        s0<Float> = acc0 as Float
        s0 = s0 + shfl_down_f64(s0, 16)
        s0 = s0 + shfl_down_f64(s0, 8)
        s0 = s0 + shfl_down_f64(s0, 4)
        s0 = s0 + shfl_down_f64(s0, 2)
        s0 = s0 + shfl_down_f64(s0, 1)
        if (l == 0) {
            if (YE == 4) { st_f32(Y + n0 * 4, s0 as Float32) } else {
                if (RS != 0) { s0 = ld_f64(RS + n0 * 8) + s0 }
                st_f64(Y + n0 * 8, s0)
            }
        }
    }
}
""")
open("kernels/" + OUTF, "w").write("\n".join(out))

# Generates rgemv5.vyb: third-generation Ridge IQ2_S / IQ3_S decode GEMVs (gemv_iq2s_r / gemv_iq3s_r).
# Same lane map and per-lane arithmetic order as gen_rgemv2.py (so results are bit-identical), but:
#  * x via two ld_v4_f32 vector loads per super-block instead of 8 scalar loads,
#  * warp reduction with shfl_down_f64 (16,8,4,2,1: same pairing as the old shared-memory tree, no
#    block barriers),
#  * PF=1: software pipeline - the next super-block's raw block bytes and x are loaded before the
#    current one is decoded, hiding the dependent global-load latency.
#  * SM=1: the IQ grid is copied to shared memory per block (the divergent grid lookups were L1-bound).
# usage: gen_rgemv5.py R out.vyb PF SM PROBE D
import sys
R = int(sys.argv[1]) if len(sys.argv) > 1 else 4
OUTF = sys.argv[2] if len(sys.argv) > 2 else "rgemv5.vyb"
PF = int(sys.argv[3]) if len(sys.argv) > 3 else 1
PROBE = int(sys.argv[5]) if len(sys.argv) > 5 else 0   # 1: memory-only probe (no decode; wrong results)
D = int(sys.argv[6]) if len(sys.argv) > 6 else 1   # prefetch depth (super-blocks in flight ahead of the decode)
SM = int(sys.argv[4]) if len(sys.argv) > 4 else 1   # 1: grid copied to shared memory (compile with --kernel-shared 8192)
out = []
w = out.append
w(f"""// GENERATED by gen_rgemv5.py (R={R} rows per warp, PF={PF}). Ridge IQ decode GEMVs, third generation.
// Launch ceil(N/{16*R}) blocks x 512 (same as rgemv4). Same params as rgemv.vyb. Bit-identical to
// gen_rgemv2.py output (same per-lane sums, same reduction pairing). Derived from llama.cpp (MIT).
""")

def hdr(name):
    w(f"""{name}(p<Int>) -> {{
    W<Int> = ld_i64(p + 0)
    X<Int> = ld_i64(p + 8)
    Y<Int> = ld_i64(p + 16)
    N<Int> = ld_i64(p + 32)
    K<Int> = ld_i64(p + 40)
    YE<Int> = ld_i64(p + 48)
    RS<Int> = ld_i64(p + 120)
    G<Int> = ld_i64(p + 128)
    tid<Int> = tid_x()
    l<Int> = tid % 32
    n0<Int> = blk_x() * {16*R} + (tid / 32) * {R}
    nsb<Int> = K / 256
    c1<Float32> = 1.0 as Float32
    c2<Float32> = 2.0 as Float32
    ch<Float32> = 0.5 as Float32
    cq<Float32> = 0.25 as Float32""")
    for r in range(R):
        w(f"    acc{r}<Float32> = 0.0")

def xload(ind, dst, base, decl):
    for e in range(8):
        t = "<Float32>" if decl else ""
        w(f"{ind}{dst}{e}{t} = ld_v4_f32({base} + {16*(e//4)}, {e%4})")

def dot(ind, r, scale, xs):
    if PROBE:
        w(f"{ind}acc{r} = acc{r} + {scale} + {xs}0 + {xs}7 + ((qhb{r} + sgb{r}) as Float32)")
        return
    for e in range(8):
        sh = "" if e % 4 == 0 else f" >> {8*(e%4)}"
        gsrc = f"g0_{r}" if e < 4 else f"g1_{r}"
        gv = f"(({gsrc}{sh}) & 255)"
        sgb = f"(sg_{r} & 1)" if e == 0 else f"((sg_{r} >> {e}) & 1)"
        w(f"{ind}w{e}_{r}<Float32> = ({gv} as Float32) * (c1 - c2 * ({sgb} as Float32))")
    w(f"{ind}pt{r}<Float32> = {xs}0 * w0_{r}")
    for e in range(1, 8):
        w(f"{ind}pt{r} = pt{r} + {xs}{e} * w{e}_{r}")
    w(f"{ind}acc{r} = acc{r} + {scale} * pt{r}")

def tail():
    w("    if (n0 < N) {")
    for r in range(R):
        w(f"""        s{r}<Float> = acc{r} as Float
        s{r} = s{r} + shfl_down_f64(s{r}, 16)
        s{r} = s{r} + shfl_down_f64(s{r}, 8)
        s{r} = s{r} + shfl_down_f64(s{r}, 4)
        s{r} = s{r} + shfl_down_f64(s{r}, 2)
        s{r} = s{r} + shfl_down_f64(s{r}, 1)
        if (l == 0) {{
            if (n0 + {r} < N) {{
                if (YE == 4) {{ st_f32(Y + (n0 + {r}) * 4, s{r} as Float32) }} else {{
                    if (RS != 0) {{ s{r} = ld_f64(RS + (n0 + {r}) * 8) + s{r} }}
                    st_f64(Y + (n0 + {r}) * 8, s{r})
                }}
            }}
        }}""")
    w("    }")
    w("}\n")

# per-type raw loads: list of (name, type, expr(bb)) ; decode emits idx/g/sg/scale from raws
IQ2 = dict(bs=82, raws=[("d", "Float32", "ld_f16({b})"),
                         ("scb", "Int", "(ld_i8({b} + 74 + ib) as Int) & 255"),
                         ("qsb", "Int", "(ld_i8({b} + 2 + l) as Int) & 255"),
                         ("qhb", "Int", "(ld_i8({b} + 66 + ib) as Int) & 255"),
                         ("sgb", "Int", "(ld_i8({b} + 34 + l) as Int) & 255")],
           pre="""        ib<Int> = l / 4
        l2<Int> = l % 4
        shs<Int> = (l2 / 2) * 4
        shq<Int> = 8 - 2 * l2""")
def iq2_dec(ind, r):
    w(f"{ind}dl{r}<Float32> = d{r} * ((((scb{r} >> shs) & 15) as Float32) + ch) * cq")
    w(f"{ind}idx{r}<Int> = qsb{r} | ((qhb{r} << shq) & 768)")
    if SM:
        w(f"{ind}g0_{r}<UInt32> = ld_shared_v2_u32(idx{r} * 8, 0)")
        w(f"{ind}g1_{r}<UInt32> = ld_shared_v2_u32(idx{r} * 8, 1)")
    else:
        w(f"{ind}g0_{r}<UInt32> = ld_i32(G + idx{r} * 8) as UInt32")
        w(f"{ind}g1_{r}<UInt32> = ld_i32(G + idx{r} * 8 + 4) as UInt32")
    w(f"{ind}sg_{r}<UInt32> = sgb{r} as UInt32")
    return f"dl{r}"
IQ2["dec"] = iq2_dec
IQ3 = dict(bs=110, raws=[("d", "Float32", "ld_f16({b})"),
                          ("scb", "Int", "(ld_i8({b} + 106 + g) as Int) & 255"),
                          ("qhb", "Int", "(ld_i8({b} + 66 + 2 * g + hf) as Int) & 255"),
                          ("qw", "Int", "(ld_u16({b} + qo) as Int) & 65535"),
                          ("sgb", "Int", "(ld_i8({b} + 74 + 8 * g + 4 * hf + l3) as Int) & 255")],
           pre="""        g<Int> = l / 8
        hf<Int> = (l % 8) / 4
        l3<Int> = l % 4
        shs<Int> = hf * 4
        sh1<Int> = 8 - 2 * l3
        sh2<Int> = 7 - 2 * l3
        qo<Int> = 2 + 16 * g + 8 * hf + 2 * l3""")
def iq3_dec(ind, r):
    w(f"{ind}db{r}<Float32> = d{r} * (c1 + c2 * (((scb{r} >> shs) & 15) as Float32))")
    w(f"{ind}i1_{r}<Int> = (qw{r} & 255) | ((qhb{r} << sh1) & 256)")
    w(f"{ind}i2_{r}<Int> = (qw{r} >> 8) | ((qhb{r} << sh2) & 256)")
    if SM:
        w(f"{ind}g0_{r}<UInt32> = ld_shared_u32(i1_{r} * 4)")
        w(f"{ind}g1_{r}<UInt32> = ld_shared_u32(i2_{r} * 4)")
    else:
        w(f"{ind}g0_{r}<UInt32> = ld_i32(G + i1_{r} * 4) as UInt32")
        w(f"{ind}g1_{r}<UInt32> = ld_i32(G + i2_{r} * 4) as UInt32")
    w(f"{ind}sg_{r}<UInt32> = sgb{r} as UInt32")
    return f"db{r}"
IQ3["dec"] = iq3_dec

def kern(name, T):
    bs = T["bs"]
    hdr(name)
    if SM:
        gb = 8192 if bs == 82 else 2048
        w(f"""    if (tid < {gb // 16}) {{
        st_shared_v4_u32(tid * 16, ld_v4_u32(G + tid * 16, 0), ld_v4_u32(G + tid * 16, 1), ld_v4_u32(G + tid * 16, 2), ld_v4_u32(G + tid * 16, 3))
    }}
    kernel_barrier()""")
    w("    if (n0 < N) {")
    w(T["pre"])
    w(f"        xr<Int> = X + l * 32")
    w(f"        rbs<Int> = nsb * {bs}")
    for r in range(R):
        w(f"        rb{r}<Int> = W + (n0 + {r}) * rbs")
        if r > 0:
            w(f"        if (n0 + {r} >= N) {{ rb{r} = rb0 }}")
    I = "            "
    if not PF:
        w("        sb<Int> = 0")
        w("        while (sb < nsb) {")
        xload(I, "x", "xr + sb * 1024", True)
        for r in range(R):
            w(f"{I}bb{r}<Int> = rb{r} + sb * {bs}")
            for (nm, ty, ex) in T["raws"]:
                w(f"{I}{nm}{r}<{ty}> = {ex.format(b='bb'+str(r))}")
            sc = T["dec"](I, r) if not PROBE else "d" + str(r)
            dot(I, r, sc, "x")
        w("            sb = sb + 1")
        w("        }")
    else:
        # prologue: raw loads of super-blocks 0..D-1 into the ring registers (stage k = sb + k)
        for k in range(D):
            w(f"        sbp{k}<Int> = {k}")
            w(f"        if (sbp{k} >= nsb) {{ sbp{k} = nsb - 1 }}")
            xload("        ", f"xn{k}_", f"xr + sbp{k} * 1024", True)
            for r in range(R):
                for (nm, ty, ex) in T["raws"]:
                    w(f"        {nm}n{k}_{r}<{ty}> = {ex.format(b='rb'+str(r)+' + sbp'+str(k)+' * '+str(bs))}")
        w("        sb<Int> = 0")
        w("        while (sb < nsb) {")
        for e in range(8):
            w(f"{I}x{e}<Float32> = xn0_{e}")
        for r in range(R):
            for (nm, ty, ex) in T["raws"]:
                w(f"{I}{nm}{r}<{ty}> = {nm}n0_{r}")
        for k in range(1, D):
            for e in range(8):
                w(f"{I}xn{k-1}_{e} = xn{k}_{e}")
            for r in range(R):
                for (nm, ty, ex) in T["raws"]:
                    w(f"{I}{nm}n{k-1}_{r} = {nm}n{k}_{r}")
        w(f"{I}sbn<Int> = sb + {D}")
        w(f"{I}if (sbn >= nsb) {{ sbn = nsb - 1 }}")
        xload(I, f"xn{D-1}_", "xr + sbn * 1024", False)
        for r in range(R):
            w(f"{I}bn{r}<Int> = rb{r} + sbn * {bs}")
            for (nm, ty, ex) in T["raws"]:
                w(f"{I}{nm}n{D-1}_{r} = {ex.format(b='bn'+str(r))}")
        for r in range(R):
            sc = T["dec"](I, r) if not PROBE else "d" + str(r)
            dot(I, r, sc, "x")
        w("            sb = sb + 1")
        w("        }")
    w("    }")
    tail()

kern("gemv_iq2s_r", IQ2)
kern("gemv_iq3s_r", IQ3)
open(OUTF, "w").write("\n".join(out))

#!/usr/bin/env python3
"""Generate native/kernels/rdelta2.vyb: a parallel GDN decode state update on the column-major
state (element (j, i) of head h at S*S*h + i*S + j), opt-in via VYB_DSP=1.

delta_step_t runs Hv blocks x S threads, each thread looping serially over all S i's (latency
bound, 48 blocks). Here a block owns 32 j's of one head and NW warps split the i range:
lane = j within the block, warp w = i slice [w*S/NW, (w+1)*S/NW). For fixed i a warp's state
access is 32 consecutive elements (coalesced). Partial acc/acq sums meet in shared memory.
Grid = Hv * (S/32) blocks x 32*NW threads. Sum order differs from delta_step_t (not bit-exact).
Variants: f64 state (delta_step_p) and f32 state (delta_step_p32, for VYB_GDN32=1).
usage: gen_rdelta2.py OUT NW
"""
import sys
OUT, NW = sys.argv[1], int(sys.argv[2])
L = []
w = L.append
w(f"// generated by native/tools/gen_rdelta2.py (NW={NW}); see that file for the layout.")
w("import vmath::{vexp}")
for name, f32 in (("delta_step_p", False), ("delta_step_p32", True)):
    es = 4 if f32 else 8
    ld = "ld_f32" if f32 else "ld_f64"
    w(f"""
{name}(p<Int>) -> {{
    Q<Int> = ld_i64(p + 0)
    Kp<Int> = ld_i64(p + 8)
    V<Int> = ld_i64(p + 16)
    G<Int> = ld_i64(p + 24)
    BE<Int> = ld_i64(p + 32)
    SIN<Int> = ld_i64(p + 40)
    SOUT<Int> = ld_i64(p + 48)
    OUT<Int> = ld_i64(p + 56)
    S<Int> = ld_i64(p + 72)
    Hk<Int> = ld_i64(p + 80)
    sc<Float> = ld_f64(p + 96)
    nb<Int> = S / 32
    h<Int> = blk_x() / nb
    jj<Int> = (blk_x() % nb) * 32 + tid_x() % 32
    wq<Int> = tid_x() / 32
    t<Int> = tid_x()
    hk<Int> = h % Hk
    while (t < S) {{
        st_shared_f64(t, ld_f64(Kp + (t + S * hk) * 8))
        st_shared_f64(256 + t, ld_f64(Q + (t + S * hk) * 8))
        t = t + {32*NW}
    }}
    kernel_barrier()
    ni<Int> = S / {NW}
    i0<Int> = wq * ni
    rw<Int> = SIN + (S * S * h + i0 * S + jj) * {es}
    st<Int> = S * {es}
    acc<Float> = 0.0
    acq<Float> = 0.0
    i<Int> = 0
    for (i in 0..ni - 1) {{
        sv<Float> = {"(" if f32 else ""}{ld}(rw + i * st){" as Float)" if f32 else ""}
        acc = acc + sv * ld_shared_f64(i0 + i)
        acq = acq + sv * ld_shared_f64(256 + i0 + i)
    }}
    st_shared_f64(512 + tid_x(), acc)
    st_shared_f64(1024 + tid_x(), acq)
    kernel_barrier()
    lj<Int> = tid_x() % 32
    ta<Float> = 0.0
    tq<Float> = 0.0
    kq<Float> = 0.0
    u<Int> = 0
    for (u in 0..{NW - 1}) {{
        ta = ta + ld_shared_f64(512 + u * 32 + lj)
        tq = tq + ld_shared_f64(1024 + u * 32 + lj)
    }}
    for (u in 0..S - 1) {{ kq = kq + ld_shared_f64(u) * ld_shared_f64(256 + u) }}
    gexp<Float> = vexp(ld_f64(G + h * 8))
    be<Float> = ld_f64(BE + h * 8)
    del<Float> = (ld_f64(V + (jj + S * h) * 8) - gexp * ta) * be
    if (wq == 0) {{ st_f64(OUT + (jj + S * h) * 8, sc * (gexp * tq + del * kq)) }}
    ww<Int> = SOUT + (S * S * h + i0 * S + jj) * {es}
    for (i in 0..ni - 1) {{
        sv3<Float> = {"(" if f32 else ""}{ld}(rw + i * st){" as Float)" if f32 else ""}
        {"st_f32" if f32 else "st_f64"}(ww + i * st, {"(" if f32 else ""}gexp * sv3 + del * ld_shared_f64(i0 + i){" as Float32)" if f32 else ""})
    }}
}}""")
open(OUT, "w").write("\n".join(L) + "\n")

# delta_step_u / delta_step_u32: delta_step_t (grid Hv x S, one thread per j, serial i) with the state
# loads batched UL at a time so UL loads are in flight per thread. Same arithmetic in the same i order
# as delta_step_t, so the f64 variant is bit-identical. usage: append mode, UL from argv[3] (default 8).
UL = int(sys.argv[3]) if len(sys.argv) > 3 else 8
L2 = []
w = L2.append
for name, f32 in (("delta_step_u", False), ("delta_step_u32", True)):
    es = 4 if f32 else 8
    ld = "ld_f32" if f32 else "ld_f64"
    cv = (lambda e: f"({e} as Float)") if f32 else (lambda e: e)
    w(f"""
{name}(p<Int>) -> {{
    Q<Int> = ld_i64(p + 0)
    Kp<Int> = ld_i64(p + 8)
    V<Int> = ld_i64(p + 16)
    G<Int> = ld_i64(p + 24)
    BE<Int> = ld_i64(p + 32)
    SIN<Int> = ld_i64(p + 40)
    SOUT<Int> = ld_i64(p + 48)
    OUT<Int> = ld_i64(p + 56)
    S<Int> = ld_i64(p + 72)
    Hk<Int> = ld_i64(p + 80)
    sc<Float> = ld_f64(p + 96)
    h<Int> = blk_x()
    j<Int> = tid_x()
    hk<Int> = h % Hk
    if (j < S) {{
        st_shared_f64(j, ld_f64(Kp + (j + S * hk) * 8))
        st_shared_f64(256 + j, ld_f64(Q + (j + S * hk) * 8))
    }}
    kernel_barrier()
    if (j < S) {{
        gexp<Float> = vexp(ld_f64(G + h * 8))
        be<Float> = ld_f64(BE + h * 8)
        kq<Float> = 0.0
        i<Int> = 0
        for (i in 0..S - 1) {{ kq = kq + ld_shared_f64(i) * ld_shared_f64(256 + i) }}
        rw<Int> = SIN + (S * S * h + j) * {es}
        st<Int> = S * {es}
        acc<Float> = 0.0
        acq<Float> = 0.0
        ib<Int> = 0
        while (ib < S) {{
            a<Int> = rw + ib * st""")
    for u in range(UL):
        w(f"            s{u}<Float> = {cv(f'{ld}(a + {u} * st)')}")
    for u in range(UL):
        w(f"            acc = acc + s{u} * ld_shared_f64(ib + {u})")
        w(f"            acq = acq + s{u} * ld_shared_f64(256 + ib + {u})")
    w(f"""            ib = ib + {UL}
        }}
        del<Float> = (ld_f64(V + (j + S * h) * 8) - gexp * acc) * be
        st_f64(OUT + (j + S * h) * 8, sc * (gexp * acq + del * kq))
        ww<Int> = SOUT + (S * S * h + j) * {es}
        ib = 0
        while (ib < S) {{
            a2<Int> = rw + ib * st
            b2<Int> = ww + ib * st""")
    for u in range(UL):
        w(f"            r{u}<Float> = {cv(f'{ld}(a2 + {u} * st)')}")
    for u in range(UL):
        v = f"gexp * r{u} + del * ld_shared_f64(ib + {u})"
        w(f"            st_f32(b2 + {u} * st, (({v}) as Float32))" if f32 else f"            st_f64(b2 + {u} * st, {v})")
    w(f"""            ib = ib + {UL}
        }}
    }}
}}""")
# delta_step_v / v32: same per-thread work as delta_step_u (bit-identical in f64) but JB threads per
# block, grid Hv*S/JB, so 4x+ more blocks are resident (j columns are independent). JB from argv[4].
JB = int(sys.argv[4]) if len(sys.argv) > 4 else 32
src = "\n".join(L2)
for a, b in (("delta_step_u32(", "delta_step_v32("), ("delta_step_u(", "delta_step_v(")):
    src = src.replace(a, b)
src = src.replace("""    h<Int> = blk_x()
    j<Int> = tid_x()
    hk<Int> = h % Hk
    if (j < S) {
        st_shared_f64(j, ld_f64(Kp + (j + S * hk) * 8))
        st_shared_f64(256 + j, ld_f64(Q + (j + S * hk) * 8))
    }""", f"""    nb<Int> = S / {JB}
    h<Int> = blk_x() / nb
    j<Int> = (blk_x() % nb) * {JB} + tid_x()
    hk<Int> = h % Hk
    t0<Int> = tid_x()
    while (t0 < S) {{
        st_shared_f64(t0, ld_f64(Kp + (t0 + S * hk) * 8))
        st_shared_f64(256 + t0, ld_f64(Q + (t0 + S * hk) * 8))
        t0 = t0 + {JB}
    }}""")
assert "delta_step_v(" in src and "nb<Int>" in src
# delta_step_w / w32: delta_step_v that caches its S x JB state tile in shared (slot 512 + i*JB + tid)
# during the first pass, so the second pass reads shared instead of re-reading DRAM (1/3 less traffic).
# Same arithmetic order: bit-identical to delta_step_t in f64. Needs (512 + S*JB)*8 bytes shared.
import re
srw = src.replace("delta_step_v32(", "delta_step_w32(").replace("delta_step_v(", "delta_step_w(")
srw = re.sub(r"( +)s(\d+)<Float> = (.*)\n", lambda m: f"{m.group(1)}s{m.group(2)}<Float> = {m.group(3)}\n{m.group(1)}st_shared_f64(512 + (ib + {m.group(2)}) * {JB} + tid_x(), s{m.group(2)})\n", srw)
srw = re.sub(r"( +)r(\d+)<Float> = .*\n", lambda m: f"{m.group(1)}r{m.group(2)}<Float> = ld_shared_f64(512 + (ib + {m.group(2)}) * {JB} + tid_x())\n", srw)
assert srw.count("ld_shared_f64(512 +") == 2 * UL
open(OUT, "a").write("\n".join(L2) + "\n" + src + "\n" + srw + "\n")

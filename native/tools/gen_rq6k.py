# Generates rq6k.vyb: Ridge Q6_K decode GEMV gemv_q6k_v (M=1). Same lane map, per-lane arithmetic
# and reduction pairing as qwen3.vyb gemv_q6k (bit-identical), but R rows per warp (default 1),
# a D-deep software prefetch ring of the raw block bytes + x, and shfl_down_f64 reduction.
# Params: gemv_q4k layout (3 row segments @0/@56/@88, RS@120). Launch ceil(Ntot/(16*R)) x 512.
# usage: gen_rq6k.py R D out.vyb
import sys
R = int(sys.argv[1]); D = int(sys.argv[2]); OUTF = sys.argv[3]
o = []; w = o.append
w(f"""// GENERATED by gen_rq6k.py (R={R}, D={D}). Ridge Q6_K decode GEMV, bit-identical to qwen3 gemv_q6k (M=1).
gemv_q6k_v(p<Int>) -> {{
    W<Int> = ld_i64(p + 0)
    X<Int> = ld_i64(p + 8)
    Y<Int> = ld_i64(p + 16)
    N<Int> = ld_i64(p + 32)
    K<Int> = ld_i64(p + 40)
    YE<Int> = ld_i64(p + 48)
    tid<Int> = tid_x()
    l<Int> = tid % 32
    n0<Int> = blk_x() * {16*R} + (tid / 32) * {R}
    NS2<Int> = ld_i64(p + 64)
    RS<Int> = ld_i64(p + 120)
    NS3<Int> = ld_i64(p + 96)
    if (n0 >= N) {{
        if (n0 < N + NS2) {{
            n0 = n0 - N
            W = ld_i64(p + 56)
            Y = ld_i64(p + 72)
            YE = ld_i64(p + 80)
            N = NS2
        }} else {{
            n0 = n0 - N - NS2
            W = ld_i64(p + 88)
            Y = ld_i64(p + 104)
            YE = ld_i64(p + 112)
            N = NS3
        }}
    }}
    nsb<Int> = K / 256
    c8<Float32> = 0.00390625 as Float32
    c256<Float32> = 256.0 as Float32
    c32<Float32> = 32.0 as Float32
    cmg<Float32> = 12582912.0 as Float32
    g<Int> = l / 16
    jj<Int> = (l % 16) * 2
    g8is<Int> = g * 8 + jj / 16
    g64jj<Int> = g * 64 + jj
    g32jj<Int> = g * 32 + jj""")
for r in range(R):
    w(f"    acc{r}<Float32> = 0.0")
XO = [0, 128, 256, 384, 4, 132, 260, 388]
RAW = [("df", "Float32", "ld_f16({b} + 208)"),
       ("s0", "Int32", "ld_i8({b} + 192 + g8is) as Int32"),
       ("s1", "Int32", "ld_i8({b} + 192 + g8is + 2) as Int32"),
       ("s2", "Int32", "ld_i8({b} + 192 + g8is + 4) as Int32"),
       ("s3", "Int32", "ld_i8({b} + 192 + g8is + 6) as Int32"),
       ("qa", "UInt32", "(ld_u16({b} + g64jj) as UInt32) & 65535"),
       ("qb", "UInt32", "(ld_u16({b} + g64jj + 32) as UInt32) & 65535"),
       ("qh", "UInt32", "(ld_u16({b} + 128 + g32jj) as UInt32) & 65535")]
def loads(ind, k, sbexpr, decl):
    t = lambda ty: f"<{ty}>" if decl else ""
    w(f"{ind}xq{k}{t('Int')} = xr + ({sbexpr}) * 1024")
    for e in range(8):
        w(f"{ind}xn{k}_{e}{t('Float32')} = ld_f32(xq{k} + {XO[e]})")
    for r in range(R):
        w(f"{ind}bn{k}_{r}{t('Int')} = rb{r} + ({sbexpr}) * 210")
        for (nm, ty, ex) in RAW:
            w(f"{ind}{nm}n{k}_{r}{t(ty)} = {ex.format(b=f'bn{k}_{r}')}")
w("    if (n0 < N) {")
w("        xr<Int> = X + (g * 128 + jj) * 4")
for r in range(R):
    w(f"        rb{r}<Int> = W + (n0 + {r}) * nsb * 210")
    if r > 0:
        w(f"        if (n0 + {r} >= N) {{ rb{r} = rb0 }}")
for k in range(D):
    w(f"        sp{k}<Int> = {k}")
    w(f"        if (sp{k} >= nsb) {{ sp{k} = nsb - 1 }}")
    loads("        ", k, f"sp{k}", True)
w("        sb<Int> = 0")
w("        while (sb < nsb) {")
I = "            "
for e in range(8):
    w(f"{I}xv{e}<Float32> = xn0_{e}")
for r in range(R):
    for (nm, ty, ex) in RAW:
        w(f"{I}{nm}{r}<{ty}> = {nm}n0_{r}")
for k in range(1, D):
    for e in range(8):
        w(f"{I}xn{k-1}_{e} = xn{k}_{e}")
    for r in range(R):
        for (nm, ty, ex) in RAW:
            w(f"{I}{nm}n{k-1}_{r} = {nm}n{k}_{r}")
w(f"{I}sbn<Int> = sb + {D}")
w(f"{I}if (sbn >= nsb) {{ sbn = nsb - 1 }}")
loads(I, D - 1, "sbn", False)
for r in range(R):
    w(f"{I}da{r}<Float32> = df{r} * (s0{r} as Float32)")
    w(f"{I}db{r}<Float32> = df{r} * (s1{r} as Float32)")
    w(f"{I}dc{r}<Float32> = df{r} * (s2{r} as Float32)")
    w(f"{I}dd{r}<Float32> = df{r} * (s3{r} as Float32)")
    for (i, q, hs, qs) in [(1, "qa", 0, 0), (2, "qb", 2, 0), (3, "qa", 6, 4), (4, "qb", 6, 4)]:
        pass
    spec = [(1, "qa", 0, 0), (2, "qb", 0, 2), (3, "qa", 4, 4), (4, "qb", 4, 6)]
    for (i, q, qsh, hsh) in spec:
        w(f"{I}v{i}_{r}<Float32> = (((({q}{r} >> {qsh}) & 3855) | (((qh{r} >> {hsh}) & 771) << 4)) as Float32)")
        w(f"{I}h{i}_{r}<Float32> = (v{i}_{r} * c8 + cmg) - cmg")
        w(f"{I}l{i}_{r}<Float32> = v{i}_{r} - h{i}_{r} * c256")
    seq = [("xv0", "da", "l1"), ("xv1", "db", "l2"), ("xv2", "dc", "l3"), ("xv3", "dd", "l4"),
           ("xv4", "da", "h1"), ("xv5", "db", "h2"), ("xv6", "dc", "h3"), ("xv7", "dd", "h4")]
    for (xv, dsc, v) in seq:
        w(f"{I}acc{r} = acc{r} + {xv} * ({dsc}{r} * ({v}_{r} - c32))")
w("            sb = sb + 1")
w("        }")
for r in range(R):
    w(f"""        s{r}<Float> = acc{r} as Float
        s{r} = s{r} + shfl_down_f64(s{r}, 16)
        s{r} = s{r} + shfl_down_f64(s{r}, 8)
        s{r} = s{r} + shfl_down_f64(s{r}, 4)
        s{r} = s{r} + shfl_down_f64(s{r}, 2)
        s{r} = s{r} + shfl_down_f64(s{r}, 1)
        if (l == 0) {{
            if (n0 + {r} < N) {{
                if (YE == 4) {{ st_f32(Y + (n0 + {r}) * 4, s{r} as Float32) }} else {{
                    if (RS != 0) {{ s{r} = ld_f64(RS + (n0 + {r}) * 8) + s{r} }}
                    st_f64(Y + (n0 + {r}) * 8, s{r})
                }}
            }}
        }}""")
w("    }")
w("}")
open(OUTF, "w").write("\n".join(o) + "\n")
